"""Телефон в поле с JS-маской: подбираем способ ввода, пока сайт не признает номер.

Живой случай (СМУ, stalmetural.ru): маска сама подставляет «+7 (» и первую цифру
введённого номера трактует как код страны. Ввод 10 национальных цифр даёт
«+1 (111) 111 111» - 10 цифр, сайт отвечает «Номер телефона должен содержать 11
цифр», форма не отправляется. Раньше именно так «лечили» первое заполнение, и у
пяти рабочих форм в отчёте стояли крестики в «Статусе» и «Уведомлении».
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                                'forms_tester'))

import test_all as t          # noqa: E402


class ПолеСМаской:
    """Поле телефона с маской «+X (XXX) XXX XXXX», как у СМУ: первая цифра
    введённого номера уходит в код страны, сайт требует ровно 11 цифр."""

    def __init__(self, сдвиг_первого_ввода: bool = False):
        self.value = ''
        self.вводов = 0
        self.сдвиг_первого_ввода = сдвиг_первого_ввода

    # ── как ведёт себя маска ──
    def _маска(self, цифры: str) -> str:
        if not цифры:
            return ''
        код, хвост = цифры[0], цифры[1:11]
        return f'+{код} ({хвост[:3]}) {хвост[3:6]} {хвост[6:]}'.rstrip()

    # ── API локатора Playwright, который использует функция ──
    def fill(self, значение, force=False, timeout=None):
        if значение == '':
            self.value = ''
            return
        цифры = ''.join(c for c in значение if c.isdigit())
        self.вводов += 1
        if self.сдвиг_первого_ввода and self.вводов == 1:
            цифры = цифры[0] + цифры          # маска задвоила код страны
        self.value = self._маска(цифры)

    def type(self, значение, delay=0, timeout=None):
        self.fill(значение)

    def input_value(self, timeout=None):
        return self.value

    def evaluate(self, js, *args):
        # единственный вызов из функции - checkValidity
        return len(''.join(c for c in self.value if c.isdigit())) == 11


def test_оценка_телефона_валидность_важнее_цифр():
    ожид = '71111111111'
    валидный_чужой = t._оценка_телефона('+7 (711) 111 1111', ожид, True)
    невалидный_свой = t._оценка_телефона('+1 (111) 111 111', ожид, False)
    assert валидный_чужой > невалидный_свой
    точный = t._оценка_телефона('+7 (111) 111 1111', ожид, True)
    assert точный > валидный_чужой


def test_маска_принимает_полный_номер_с_первого_раза():
    поле = ПолеСМаской()
    знач, валид = t.вставить_телефон_в_маску(поле, '71111111111', лог=lambda *_: None)
    assert валид and знач == '+7 (111) 111 1111'
    assert поле.вводов == 1, 'лишние попытки при удачном первом вводе'


def test_сдвинутый_маской_номер_чинится_а_не_ломается():
    """Первый ввод маска исказила - подбор доводит поле до валидного и ТОЧНОГО
    номера, а не оставляет «+1 (111) 111 111» (10 цифр), как раньше."""
    поле = ПолеСМаской(сдвиг_первого_ввода=True)
    знач, валид = t.вставить_телефон_в_маску(поле, '71111111111', лог=lambda *_: None)
    assert валид, f'поле осталось невалидным: {знач}'
    assert ''.join(c for c in знач if c.isdigit()) == '71111111111'


def test_пустой_номер_не_ломает_подбор():
    поле = ПолеСМаской()
    знач, валид = t.вставить_телефон_в_маску(поле, '', лог=lambda *_: None)
    assert знач == '' and валид is False
