"""МПЭ, домен Баку: формы адресуются по подписям, а не по именам полей.

Прогон 21.08.2026 по mepen.az: три формы стояли ✗ со «Статусом: Ошибка» и
прочерком в «Уведомлении пользователю». Причина - имена полей на .az ДРУГИЕ,
хотя подписи и placeholder'ы везде одинаковые (проверено на всех шести
доменах проекта):

  форма                     .ru/.kz/.by/.uz/.kg      .az
  «Нужна консультация»      form_text_14 / _15       form_text_17 / _18
  «Нашли дешевле»           form_text_18/_19/_20     form_text_10/_11/_12
  чекаут: Ф.И.О.            ORDER_PROP_1             ORDER_PROP_5
  чекаут: E-Mail            ORDER_PROP_2             ORDER_PROP_1
  чекаут: Телефон           ORDER_PROP_3             ORDER_PROP_2
  чекаут: Адрес доставки    ORDER_PROP_7             ORDER_PROP_12

Обрати внимание на ловушку: form_text_18 в РФ - это ИМЯ формы «Нашли
дешевле», а на .az - ТЕЛЕФОН формы «Нужна консультация». Ровно поэтому
модалки не находились, а чекаут заполнялся кашей (в E-Mail - имя, в телефон
- почта) и не пускал дальше: «не заполнено обязательное поле».
"""
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / 'forms_tester'))

from projects.mpe import config as mpe   # noqa: E402


def _блок(тип):
    return next(б for б in mpe.СТРАНИЦЫ_ДЛЯ_ПРОВЕРКИ if б['тип'] == тип)


def _шаг_формы(блок, название):
    for сц in блок['сценарии']:
        for ш in сц['шаги']:
            if ш.get('действие') == 'форма' and ш.get('название') == название:
                return ш
    raise AssertionError(f'шаг формы «{название}» не найден')


# ── модалки товара ───────────────────────────────────────────────────

def test_модалки_адресуются_по_подписям_а_не_по_именам():
    """Имена form_text_N на .az свои, а placeholder'ы одинаковы везде."""
    блок = _блок('Товар')
    for название in ('Нужна консультация по этому товару?',
                     'Нашли дешевле? Снизим цену!'):
        шаг = _шаг_формы(блок, название)
        assert 'form_text' not in шаг['css'], f'{название}: селектор по имени поля'
        assert all(k.startswith('css:') for k in шаг['поля']), шаг['поля']
    print('✓ обе модалки товара цепляются за подписи полей')


def test_консультация_не_путается_с_нашли_дешевле():
    """У обеих форм есть Имя*/Телефон*; отличает их «Ссылка на товар»."""
    блок = _блок('Товар')
    конс = _шаг_формы(блок, 'Нужна консультация по этому товару?')['css']
    деш = _шаг_формы(блок, 'Нашли дешевле? Снизим цену!')['css']

    assert ':not(:has(input[placeholder*=\'Ссылка\']))' in конс.replace('"', "'")
    assert 'Ссылка на товар' in деш
    print('✓ формы различаются по полю «Ссылка на товар»')


# ── чекаут ───────────────────────────────────────────────────────────

def test_у_баку_свой_блок_оформления():
    рф, az = _блок('Оформление'), _блок('Оформление_AZ')

    assert рф.get('кроме_городов') == ['Баку'], 'РФ-блок должен пропускать Баку'
    assert az.get('только_города') == ['Баку'], 'AZ-блок только для Баку'
    assert 'Оформление_AZ' in mpe.СТРАНИЦЫ, 'нет адреса страницы для блока'
    print('✓ Баку идёт своим блоком, остальные города - прежним')


def test_карта_полей_чекаута_баку_по_живым_именам():
    """Имена сняты с mepen.az вживую: _5 Ф.И.О, _1 E-Mail, _2 Телефон,
    _12 Адрес доставки."""
    поля = _шаг_формы(_блок('Оформление_AZ'), 'Оформление заказа Мепэн')['поля']

    assert поля['ORDER_PROP_5'] == 'ИМЯ'
    assert поля['ORDER_PROP_1'] == 'ПОЧТА'
    assert поля['ORDER_PROP_2'] == 'ТЕЛЕФОН'
    assert 'Баку' in поля['ORDER_PROP_12']
    print('✓ карта полей чекаута Баку совпадает с живой разметкой')


def test_рф_карта_не_поехала():
    """Правка адресная: у остальных доменов чекаут как был."""
    поля = _шаг_формы(_блок('Оформление'), 'Оформление заказа Мепэн')['поля']

    assert поля['ORDER_PROP_1'] == 'ИМЯ'
    assert поля['ORDER_PROP_2'] == 'ПОЧТА'
    assert поля['ORDER_PROP_3'] == 'ТЕЛЕФОН'
    assert 'ORDER_PROP_5' not in поля
    print('✓ РФ/СНГ-карта чекаута не изменилась')


def test_обе_колонки_заказа_называются_одинаково():
    """Иначе в отчёте появится вторая колонка и сцепка с админкой поедет."""
    for тип in ('Оформление', 'Оформление_AZ'):
        блок = _блок(тип)
        проверки = [ш for сц in блок['сценарии'] for ш in сц['шаги']
                    if ш.get('действие') == 'проверить']
        assert проверки, тип
        assert проверки[0]['название'] == 'Оформление заказа Мепэн', тип
    print('✓ у обоих блоков одно название колонки заказа')
