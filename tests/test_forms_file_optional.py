"""Необязательное вложение не должно топить вердикт всей формы.

Случай АПС («Экспресс заявка»): поле файла необязательное, но скрипт сайта
падает на КАЖДОМ вложении ещё до отправки. Раньше движок прикреплял тест-PDF
всем формам с файловым полем, заявка не уходила, и рабочая форма получала
«Нет подтверждения». Теперь файл прикрепляем только когда он обязателен, а
сломанный загрузчик отмечаем отдельной находкой.
"""
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / 'forms_tester'))

import test_all as t


def _проба(принятые_обычные=(), принятые_опасные=(), большой=None):
    return {'было_поле': True, 'проверено': 5,
            'принятые_обычные': list(принятые_обычные),
            'принятые_опасные': list(принятые_опасные),
            'отклонённые': [], 'большой_принят': большой}


def test_сломанный_загрузчик_это_дефект():
    """Форма без файла отправляется, с файлом - никогда: виноват загрузчик."""
    кол, дет = t.фильтр_файлов_вердикт(_проба(), форма_без_файла_работает=True)

    assert кол.startswith('✗'), кол
    assert 'загрузка файла не работает' in кол
    assert 'теряется' in дет
    print('✓ рабочая форма + ни одного файла = дефект загрузчика, а не «проверить»')


def test_без_данных_о_форме_остаётся_проверить():
    """Не знаем, отправляется ли форма без файла - вердикт прежний, мягкий."""
    кол, дет = t.фильтр_файлов_вердикт(_проба())

    assert кол.startswith('проверить'), кол
    assert 'вручную' in дет
    print('✓ без контекста - прежнее «проверьте вручную»')


def test_форма_сама_не_отправляется_не_вина_загрузчика():
    """Если и без файла подтверждения нет - загрузчик не при чём."""
    кол, _ = t.фильтр_файлов_вердикт(_проба(), форма_без_файла_работает=False)

    assert кол.startswith('проверить'), кол
    print('✓ молчащая форма не записывается в сломанные загрузчики')


def test_принятые_типы_разбираются_как_раньше():
    """Правка не трогает основной сценарий: опасные и посторонние типы - ✗."""
    кол, дет = t.фильтр_файлов_вердикт(
        _проба(принятые_обычные=['.pdf'], принятые_опасные=['.php']),
        форма_без_файла_работает=True)
    assert кол.startswith('✗') and 'ОПАСНЫЕ' in дет

    кол2, _ = t.фильтр_файлов_вердикт(
        _проба(принятые_обычные=['.pdf'], большой=False),
        форма_без_файла_работает=True)
    assert кол2.startswith('корректно'), кол2
    print('✓ обычные вердикты фильтра не изменились')
