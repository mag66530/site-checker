"""Маска телефона на СНГ-доменах: мгновенная вставка ломает ФОРМАТ номера.

Живой случай ИМП (прогон 21.08.2026): в Москве все формы зелёные, а на
Минске / Астане / Ташкенте ВСЕ красные - «Ошибка», «Уведомление: Нет»,
«Данные дошли: Проверить». Руками формы работают.

На .by/.kz/.uz у поля telephone стоит pattern местного формата, а маску
вешает JS на события ввода. Проверено вживую (Playwright, 21.08.2026):

    .by   fill '+7 (111) 111-11-11' → '+375 (71) 111-11-'   НЕВАЛИДНО
    .by   очистка + посимвольно     → '+375 (71) 111-11-11' валидно
    .kz   fill                      → '+7 (711) 111-11-'    НЕВАЛИДНО
    .uz   fill                      → '+998 (71) 111-11-'   НЕВАЛИДНО
    .ru   fill                      → '+7 (111) 111-11-11'  валидно (pattern нет)

Ключевая особенность случая: ЦИФР в обрезанном номере ровно столько же,
сколько в нашем, - перекос виден только по checkValidity. Поэтому подбор
способа ввода (вставить_телефон_в_маску) должен запускаться и тогда, когда
цифры совпали, а поле невалидно.

Случай СМУ (маска сдвигает код страны) закрыт тестами в
tests/test_form_phone_mask.py - там же проверяется сам перебор способов.
"""
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / 'forms_tester'))

import test_all as t          # noqa: E402


class ПолеСНГ:
    """Поле под маской СНГ-домена (как на inmetprom.by/.kz/.uz).

    Мгновенная вставка обрабатывается как один кусок и обрезает номер на две
    цифры; посимвольный ввод после полной очистки даёт корректное значение.
    Валидность - строго по длине национальной части (аналог pattern)."""

    def __init__(self, префикс: str = '+375 (', длина_нац: int = 9):
        self.префикс = префикс
        self.длина_нац = длина_нац
        self.value = ''
        self.очищено_полностью = False

    def fill(self, значение, force=False, timeout=None):
        if значение == '':
            # Как на живом сайте: маска оставляет свой префикс.
            self.value = self.префикс
            self.очищено_полностью = False
            return
        цифры = ''.join(c for c in значение if c.isdigit())
        нац = цифры[-self.длина_нац:]
        if not self.очищено_полностью:
            нац = нац[:-2]                 # вставка в «недочищенное» поле режет
        self.value = self.префикс + нац
        self.очищено_полностью = False

    def type(self, значение, delay=0, timeout=None):
        цифры = ''.join(c for c in значение if c.isdigit())
        нац = цифры[-self.длина_нац:]
        if not self.очищено_полностью:
            нац = нац[:-2]                 # дописали к остатку - снова обрезано
        self.value = self.префикс + нац
        self.очищено_полностью = False

    def input_value(self, timeout=None):
        return self.value

    def evaluate(self, js, *args):
        if 'checkValidity' in js:
            return len(self.value) - len(self.префикс) == self.длина_нац
        # JS-сброс value с событиями - единственная полная очистка
        self.value = ''
        self.очищено_полностью = True
        return None


def test_вставка_ломает_формат_а_подбор_чинит():
    for префикс in ('+375 (', '+7 (', '+998 ('):
        поле = ПолеСНГ(префикс)
        поле.fill('+7 (111) 111-11-11', force=True)
        assert not поле.evaluate('checkValidity'), 'вставка должна ломать номер'

        знач, валид = t.вставить_телефон_в_маску(поле, '71111111111',
                                                 лог=lambda *_: None)

        assert валид, f'{префикс}: поле осталось невалидным ({знач})'
    print('✓ на .by/.kz/.uz подбор доводит номер до валидного')


def test_очистка_сбрасывает_остаток_маски():
    """Одного fill('') мало: маска оставляет свой префикс, и следующий ввод
    дописывается к остатку. Нужен ещё JS-сброс value с событиями."""
    поле = ПолеСНГ()
    поле.fill('+7 (111) 111-11-11', force=True)

    t._очистить_поле_под_маской(поле)

    assert поле.value == ''
    assert поле.очищено_полностью
    print('✓ поле очищается полностью, без остатков маски')


def test_посимвольный_ввод_есть_в_списке_способов():
    """Именно он чинит СНГ-домены ИМП - без него подбор перебирал бы только
    варианты мгновенной вставки и не нашёл рабочего."""
    поле = ПолеСНГ()
    поле.вводы = []

    class Следящее(ПолеСНГ):
        def __init__(с):
            super().__init__()
            с.способы = []

        def fill(с, значение, force=False, timeout=None):
            if значение != '':
                с.способы.append(('fill', значение))
            super().fill(значение, force, timeout)

        def type(с, значение, delay=0, timeout=None):
            с.способы.append(('type', значение))
            super().type(значение, delay, timeout)

    следящее = Следящее()
    следящее.fill('+7 (111) 111-11-11', force=True)
    следящее.способы.clear()
    t.вставить_телефон_в_маску(следящее, '71111111111', лог=lambda *_: None)

    assert ('type', '71111111111') in следящее.способы, следящее.способы
    print('✓ полный номер пробуется и посимвольно')


def test_валидность_поля_читается_у_браузера():
    class Без:
        def evaluate(self, js, *a):
            raise RuntimeError('нет метода')

    assert t.поле_валидно(Без()) is True     # дефект не выдумываем
    print('✓ нет нативной валидации - считаем поле валидным')


def test_пустой_номер_не_ломает_подбор():
    поле = ПолеСНГ()
    знач, валид = t.вставить_телефон_в_маску(поле, '', лог=lambda *_: None)

    assert знач == '' and валид is False
    print('✓ пустой тест-номер обрабатывается без падения')
