"""Маска телефона на СНГ-доменах: мгновенная вставка ломает номер.

Живой случай ИМП (прогон 21.08.2026): в Москве все формы зелёные, а на
Минске / Астане / Ташкенте ВСЕ красные - «Ошибка», «Уведомление: Нет»,
«Данные дошли: Проверить». Руками формы работают.

Причина - не сайт. На .by/.kz/.uz у поля telephone стоит pattern местного
формата, а маску вешает JS на события ввода. Тул заполнял поле fill() -
значение кладётся целиком, маска обрабатывает его как одну вставку и выдаёт
обрезанный номер. Проверено вживую (Playwright, 21.08.2026):

    .by   fill '+7 (111) 111-11-11' → '+375 (71) 111-11-'   НЕВАЛИДНО
    .by   очистка + посимвольно     → '+375 (71) 111-11-11' валидно
    .kz   fill                      → '+7 (711) 111-11-'    НЕВАЛИДНО
    .uz   fill                      → '+998 (71) 111-11-'   НЕВАЛИДНО
    .ru   fill                      → '+7 (111) 111-11-11'  валидно (pattern нет)

Браузер блокировал отправку («Please match the requested format»), POST не
уходил - и вся страна стояла «Ошибкой». Старая проверка «маска съела цифры»
молчала: цифр ровно столько же, испорчен только формат.
"""
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / 'forms_tester'))

import test_all as t          # noqa: E402


class _Поле:
    """Мини-заглушка Playwright-локатора поля под маской.

    Повторяет поведение живых сайтов ИМП: мгновенная вставка (fill) даёт
    обрезанное значение, посимвольный ввод после сброса value - корректное.
    """

    def __init__(self, префикс: str, длина_нац: int = 9):
        self.префикс = префикс          # что подставляет маска: '+375 (' и т.п.
        self.длина_нац = длина_нац
        self.value = ''
        self.вводов = 0

    # — то, что дёргает наш код —
    def evaluate(self, js, *a):
        if 'checkValidity' in js:
            return self.валидно()
        self.value = ''                 # сброс value с событиями
        return None

    def type(self, текст, delay=0, timeout=0):
        self.вводов += 1
        цифры = ''.join(ch for ch in текст if ch.isdigit())
        # маска сама ставит код страны и берёт последние нац. цифры
        нац = цифры[-self.длина_нац:]
        self.value = self.префикс + нац

    def fill(self, текст, force=False, timeout=0):
        if not текст:
            self.value = self.префикс   # маска оставляет свой префикс
            return
        цифры = ''.join(ch for ch in текст if ch.isdigit())
        self.value = self.префикс + цифры[-self.длина_нац:][:-2]   # обрезано

    def input_value(self, timeout=0):
        return self.value

    def валидно(self):
        нац = self.value[len(self.префикс):]
        return len(нац) == self.длина_нац


# ── варианты номера ──────────────────────────────────────────────────

def test_варианты_номера():
    """Сначала номер как в конфиге, потом местный формат без кода страны:
    маску вида «+375 (__) …» российский код только путает."""
    assert t.варианты_телефона('+7 (111) 111-11-11') == [
        '+7 (111) 111-11-11', '1111111111', '71111111111']
    assert t.варианты_телефона('') == []
    print('✓ порядок вариантов: как в конфиге → местный → голые цифры')


# ── валидность поля ──────────────────────────────────────────────────

def test_поле_без_checkValidity_считаем_валидным():
    class Без:
        def evaluate(self, js, *a):
            raise RuntimeError('нет метода')

    assert t.поле_валидно(Без()) is True
    print('✓ нет нативной валидации - дефект не выдумываем')


# ── починка ввода ────────────────────────────────────────────────────

def test_посимвольный_ввод_чинит_маску_снг():
    for префикс in ('+375 (', '+7 (', '+998 ('):
        поле = _Поле(префикс)
        поле.fill('+7 (111) 111-11-11', force=True)

        assert not поле.валидно(), 'вставка должна ломать номер (как на сайте)'
        assert t.ввести_телефон_под_маску(поле, '+7 (111) 111-11-11')
        assert поле.валидно(), префикс
    print('✓ на .by/.kz/.uz номер вводится посимвольно и проходит валидацию')


def test_если_ни_один_вариант_не_подошёл():
    """Поле, которое не принимает ничего: честно возвращаем False - выше по
    коду это станет «маска не принимает тест-номер», а не молчаливым ✗."""
    class Глухое(_Поле):
        def валидно(self):
            return False

    assert t.ввести_телефон_под_маску(Глухое('+375 ('), '+7 (111) 111-11-11') is False
    print('✓ безнадёжное поле помечается честно')


def test_валидное_поле_не_перезаполняем():
    """На .ru поле после fill валидно - трогать его нельзя: перевод в
    «местный формат» там ничего не улучшит, а лишний ввод ломает маску."""
    поле = _Поле('+7 (', длина_нац=10)
    поле.value = '+7 (111) 111-11-11'
    поле.валидно = lambda: True

    # код вызывает ввести_телефон_под_маску ТОЛЬКО когда поле невалидно
    assert t.поле_валидно(поле) is True
    assert поле.вводов == 0
    print('✓ валидное поле остаётся как есть')
