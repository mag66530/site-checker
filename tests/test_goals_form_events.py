# -*- coding: utf-8 -*-
"""Подтверждение целей-конструкторов («Отправка формы») по событию Метрики.

У таких целей нет reachGoal в коде сайта - единственный внешний признак это
хит счётчика page-url=form://. Проверяем разбор хита и сопоставление
«цель ↔ отправленная форма»."""
import sys
from pathlib import Path

import goals_tester as G

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'forms_tester'))
import test_all as T  # noqa: E402


def test_хит_метрики_распознаётся():
    url = ("https://mc.yandex.ru/watch/106257960/1?page-url=form%3A%2F%2F"
           "shopmet.ru%2F%3Fp%3DFA1A1&page-ref=https%3A%2F%2Fshopmet.ru%2F")
    assert T._метрика_событие(url) == "форма"
    btn = "https://mc.yandex.ru/watch/1/1?page-url=btn%3A%2F%2Fshopmet.ru%2F"
    assert T._метрика_событие(btn) == "кнопка"
    # обычный хит просмотра страницы - не событие
    assert T._метрика_событие(
        "https://mc.yandex.ru/watch/1/1?page-url=https%3A%2F%2Fshopmet.ru%2F") == ""
    # чужой домен вообще не разбираем
    assert T._метрика_событие("https://example.com/?page-url=form://x/") == ""


def test_цель_сопоставляется_с_формой():
    формы = ["Хочу скидку", "Купить в 1 клик", "Оформление заказа",
             "Отправить заявку"]
    # имя формы в кавычках - самый точный признак
    assert G._цель_про_форму(
        'Оставить заявку в карточке товара ("Хочу скидку")', формы) == "Хочу скидку"
    assert G._цель_про_форму(
        'Оставить заявку в карточке товара ("Купить в 1 клик")',
        формы) == "Купить в 1 клик"
    # по месту - «через корзину» ловит форму оформления
    assert G._цель_про_форму("Отправка заявки через корзину",
                             формы) == "Оформление заказа"
    # «все формы» подтверждается любой отправкой
    assert G._цель_про_форму("Оставить заявку (Все формы)", формы) == формы[0]
    # если форм не отправляли - подтверждать нечем
    assert G._цель_про_форму("Оставить заявку (Все формы)", []) is None
    # чужая цель не притягивается к случайной форме
    assert G._цель_про_форму("Подписка на рассылку", формы) is None
