def test_ожидаемые_только_те_что_дёргаем_сами():
    план = G._план_страна('mtt', 'https://met-trans.ru')
    assert set(план['ожидаемые']) == {'link-callback', '404error'}


def test_план_мтт_свой_и_с_404():
    план = G._план_страна('mtt', 'https://met-trans.ru')
    urls = [u for _n, u, _c in план['страницы']]
    assert 'https://met-trans.ru/contacts' in urls          # url-цель «Контакты»
    assert any('404' in u or 'nesusch' in u for u in urls)  # ради цели 404error
    assert not [u for u in urls if '/catalog/' in u]        # раздела /catalog нет


def test_у_армении_свой_план():
    """На met-trans.am новый интерфейс: другие кнопки, поэтому и клики другие."""
    ru = G._план_страна('mtt', 'https://met-trans.ru')
    am = G._план_страна('mtt-am', 'https://met-trans.am')
    assert ru['страницы'][0][2] != am['страницы'][0][2]


def test_каталоги_мтт_из_api():
    ожидание = {'mtt': 42934624, 'mtt-rb': 61870072, 'mtt-kz': 61807483,
                'mtt-am': 91075607, 'mtt-az': 94030995, 'mtt-uz': 94030939,
                'mtt-kg': 94030854}
    for pid, счётчик in ожидание.items():
        c = json.loads((ROOT / 'catalogs' / f'goals-{pid}.json')
                       .read_text(encoding='utf-8'))
        assert c['счётчик'] == счётчик, pid
        assert 'API Метрики' in c['источник'], pid


