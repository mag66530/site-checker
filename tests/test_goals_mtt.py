# -*- coding: utf-8 -*-
"""МТТ в «Проверке целей» + правило «перехват работал, а цель молчит».

Сайт на AngularJS: reachGoal-ов в разметке нет, статически привязку не увидеть,
поэтому раньше ЛЮБАЯ непойманная цель уезжала в серое «Не проверено». Но если в
том же прогоне другие ожидаемые цели поймались, значит перехват работает - и
молчание конкретной цели это находка, а не наша слепота. На МТТ так вскрылось,
что цель «Отслеживание 404 ошибки» не приходит вообще (проверено отдельно
браузером: на 404-й странице сайт не шлёт ни одного goal-запроса).
"""
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import goals_tester as G

ROOT = Path(__file__).parent.parent


def _прогон(fired, страницы=('https://met-trans.ru/',)):
    return {'fired': set(fired), 'привязки': set(), 'код': '',
            'идентификаторы': set(),
            'страницы': [{'название': 'Стр', 'url': u, 'код': 200,
                          'счётчик': True, 'визит': True} for u in страницы]}


def _каталог(цели):
    return {'проект': 'Тест', 'счётчик': '1', 'домен': 'https://met-trans.ru',
            'цели': цели}


_ЦЕЛИ = [
    {'тип': 'js', 'номер': '1', 'название': 'Обратный звонок', 'условие': '',
     'идентификаторы': ['link-callback'], 'содержит': False, 'url_часть': ''},
    {'тип': 'js', 'номер': '2', 'название': 'Отслеживание 404 ошибки',
     'условие': '', 'идентификаторы': ['404error'], 'содержит': False,
     'url_часть': ''},
]


def _строки(pid, fired, monkeypatch):
    monkeypatch.setattr(G, '_результаты_форм', lambda p: {})
    monkeypatch.setattr(G, '_формные_цели', lambda p: set())
    monkeypatch.setattr(G, '_формные_url', lambda p: set())
    res = G._классифицировать(pid, _каталог(_ЦЕЛИ), _прогон(fired))
    return {s['название']: s for s in res['строки']}


def test_молчащая_цель_становится_находкой(monkeypatch):
    """link-callback поймали - значит перехват жив; 404error молчит → красное."""
    строки = _строки('mtt', {'link-callback'}, monkeypatch)
    assert строки['Обратный звонок']['статус'] == 'Сработала'
    assert строки['Отслеживание 404 ошибки']['статус'] == 'НЕ сработала'


def test_без_единой_пойманной_цели_красного_нет(monkeypatch):
    """Ничего не поймали - возможно, сломан сам перехват (прокси, блокировка).
    Обвинять сайт в этом случае нельзя: остаётся честное «Не проверено»."""
    строки = _строки('mtt', set(), monkeypatch)
    assert строки['Отслеживание 404 ошибки']['статус'] == 'Не проверено'
    assert строки['Обратный звонок']['статус'] == 'Не проверено'


def test_цели_вне_ожидаемых_красными_не_становятся(monkeypatch):
    """Цель на ОТПРАВКУ заявки прогон не триггерит (заявки не шлём), поэтому её
    молчание - не находка. Такие цели в «ожидаемые» не попадают."""
    цели = _ЦЕЛИ + [{'тип': 'js', 'номер': '3', 'название': 'Кнопка Отправить',
                     'условие': '', 'идентификаторы': ['submit-form'],
                     'содержит': False, 'url_часть': ''}]
    monkeypatch.setattr(G, '_результаты_форм', lambda p: {})
    monkeypatch.setattr(G, '_формные_цели', lambda p: set())
    monkeypatch.setattr(G, '_формные_url', lambda p: set())
    res = G._классифицировать('mtt', _каталог(цели), _прогон({'link-callback'}))
    статус = {s['название']: s['статус'] for s in res['строки']}
    # Такая цель уходит в «через формы» (и прячется как заглушка, пока формы не
    # прогоняли) - главное, что она НЕ красная.
    assert статус.get('Кнопка Отправить') != 'НЕ сработала'


