"""МТТ, блок «Корзина»: почему Москва показывала «товар не кладётся».

Прогон 21.08.2026: у Москвы строка «Корзина» = Ошибка «Из карточки товара
товар не кладётся в корзину», хотя вручную заказ из корзины оформляется.
Разбор живьём:

1. Признак товара в корзине был '.cart, [class*=cart]'. На met-trans.ru таких
   узлов 17, и ПЕРВЫЙ из них - скрытый '.header__cart' в шапке. Ожидание
   видимости падало всегда, независимо от того, есть товар или нет. Живой
   признак - кнопка «Перейти к оформлению»: при пустой корзине её нет, с
   товаром она видна.

2. Товаром для сценария был ТОВАР (шнур асбестовый) - он существует только на
   met-trans.ru, а на .by и .kz отдаёт 404. Там сценарий падал ещё на клике по
   галочке и в отчёт не попадал вовсе. ТОВАР_ТАБЛИЦА (болт М16х50) живой на
   всех доменах.

3. Страницы /cart нет на большинстве СНГ-доменов: 404 у mtt.kz,
   mettransterminal.kz, mtt-karaganda.kz, mtt-shymkent.kz, met-trans.by,
   met-trans.az, met-trans.uz. Корзина есть только у met-trans.ru,
   met-trans.am (свой блок «АМ_корзина») и mtt.kg. Такие города вынесены в
   _БЕЗ_КОРЗИНЫ - иначе «Заявка из корзины» отправлялась с 404-страницы (кнопка
   «Отправить заявку» есть в подвале любой страницы) и выглядела проверенной.
"""
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / 'forms_tester'))

from projects.mtt import config as mtt   # noqa: E402


def _блок(тип):
    return next(б for б in mtt.СТРАНИЦЫ_ДЛЯ_ПРОВЕРКИ if б['тип'] == тип)


def _шаги(тип, название):
    блок = _блок(тип)
    сц = next(с for с in блок['сценарии'] if с['название'] == название)
    return сц['шаги']


def test_признак_товара_в_корзине_живой():
    """«Перейти к оформлению» появляется только при товаре в корзине -
    в отличие от прежнего '.cart, [class*=cart]', который цеплял скрытую
    иконку корзины в шапке и падал всегда."""
    шаг = next(ш for ш in _шаги('Корзина', 'Оформление заказа')
               if ш.get('действие') == 'проверить_корзину')

    assert 'Перейти к оформлению' in шаг['признак_товар_css']
    assert 'visible=true' in шаг['признак_товар_css']
    assert '[class*=cart]' not in str(шаг)
    print('✓ корзина проверяется по кнопке «Перейти к оформлению»')


def test_товар_сценария_живой_на_всех_доменах():
    """Шнур асбестовый есть только на .ru (на .by/.kz — 404), болт М16х50 -
    везде."""
    переход = next(ш for ш in _шаги('Корзина', 'Оформление заказа')
                   if ш.get('действие') == 'перейти')

    assert переход['url'] == mtt.ТОВАР_ТАБЛИЦА
    assert переход['url'] != mtt.ТОВАР
    print('✓ заказ собирается на товаре, который есть на всех доменах')


def test_города_без_корзины_исключены():
    блок = _блок('Корзина')
    кроме = блок['кроме_городов']

    for город in ('Минск', 'Алматы', 'Баку', 'Ташкент', 'Караганда',
                  'Нур-Султан (Астана)'):
        assert город in кроме, город
    assert 'Ереван' in кроме, 'Ереван идёт своим блоком'
    print('✓ города без страницы корзины в блок не попадают')


def test_города_с_корзиной_остались():
    """У met-trans.ru и mtt.kg корзина есть - их исключать нельзя."""
    кроме = _блок('Корзина')['кроме_городов']

    for город in ('Москва', 'Бишкек', 'Ош', 'Екатеринбург'):
        assert город not in кроме, город
    print('✓ Москва, Бишкек и Ош проверяются как раньше')


def test_заявка_из_корзины_осталась_в_том_же_блоке():
    """Это ДРУГАЯ форма (обычная заявка со страницы корзины), а не заказ -
    она должна остаться отдельным сценарием того же блока."""
    блок = _блок('Корзина')
    названия = [с['название'] for с in блок['сценарии']]

    assert названия == ['Оформление заказа', 'Заявка из корзины'], названия
    print('✓ заказ и заявка из корзины - два разных сценария')
