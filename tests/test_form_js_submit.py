"""Формы, отправку которых делает JS, нельзя проверять «по коду».

Живой случай МПЭ, «Обратная связь (Контакты)», mepen.ru/contacts/:
в разметке `<form id="contactForm">` вообще без атрибутов, а скрипт шаблона
(components/bitrix/news.detail/detail_contacts/script.js) перехватывает
submit и шлёт fetch('/local/ajax/sendMail.php') с JSON-телом; подтверждение
показывает модалкой #successModal с текстом «Спасибо, ваша заявка принята!».

Тул видел форму в статическом HTML, поэтому шёл быстрым путём (requests):
POST уходил на саму страницу /contacts/, сайт отвечал обычным HTML с кодом
200, в отчёт попадало «успешно», а колонка «Уведомление пользователю» не
заполнялась вовсе - в матрице «–». То есть прочерк был лишь симптомом:
заявка нашим тулом не отправлялась.
"""
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / 'forms_tester'))

import test_all as t             # noqa: E402
from bs4 import BeautifulSoup    # noqa: E402


def _форма(html: str):
    return BeautifulSoup(html, 'html.parser').find('form')


# ── распознавание JS-формы ───────────────────────────────────────────

def test_форма_мпэ_без_action_и_method_идёт_в_браузер():
    форма = _форма('<form id="contactForm">'
                   '<input name="name"><input name="phone"></form>')

    assert t.форма_отправляется_js(форма)
    print('✓ форма без action/method распознана как JS-форма')


def test_обычные_формы_остаются_на_быстром_пути():
    """Bitrix-форма шлёт POST на ту же страницу - у неё есть method, и
    проверять её по коду можно (это быстро и без браузера)."""
    с_методом = _форма('<form method="post"><input name="name"></form>')
    с_экшеном = _форма('<form action="/ajax/form.php"><input name="name"></form>')
    оба = _форма('<form action="/form.php" method="post"></form>')

    assert not t.форма_отправляется_js(с_методом)
    assert not t.форма_отправляется_js(с_экшеном)
    assert not t.форма_отправляется_js(оба)
    assert not t.форма_отправляется_js(None)
    print('✓ формы с action или method по коду проверяются как раньше')


# ── уведомление пользователю из ответа сервера ───────────────────────

def test_уведомление_из_json_ответа():
    assert t.уведомление_из_ответа('{"success": true}', {'success': True}) == \
        'Да (подтверждение в ответе сервера)'
    assert t.уведомление_из_ответа('{"ok": true}', {'ok': True}) == \
        'Да (подтверждение в ответе сервера)'
    print('✓ ajax-ответ success/ok = подтверждение пользователю')


def test_уведомление_из_текстового_ответа():
    assert t.уведомление_из_ответа('Спасибо, ваша заявка принята!') == \
        'Да (подтверждение в ответе сервера)'
    assert t.уведомление_из_ответа('<div>Сообщение отправлено</div>') == \
        'Да (подтверждение в ответе сервера)'
    print('✓ короткий ответ обработчика с фразой успеха тоже засчитываем')


def test_полную_страницу_не_считаем_подтверждением():
    """В разметке страницы попап «Спасибо» лежит скрытым - его никто не
    показывал. Иначе получили бы ложное «Да» ровно там, где и был баг."""
    страница = ('<!doctype html><html><body>'
                + '<div class="modal" style="display:none">Спасибо, ваша '
                  'заявка принята!</div>' + 'текст ' * 5000 + '</body></html>')

    assert t.уведомление_из_ответа(страница) == ''
    print('✓ HTML-страница целиком за подтверждение не считается')


def test_нет_признаков_значит_пусто_а_не_нет():
    """Пусто → в матрице «–» («не смогли увидеть»), а не ✗ «нет
    уведомления»: попап может рисоваться на клиенте."""
    assert t.уведомление_из_ответа('OK') == ''
    assert t.уведомление_из_ответа('') == ''
    assert t.уведомление_из_ответа(None) == ''
    print('✓ без признаков колонка остаётся пустой, ложного ✗ нет')


def test_прочерк_а_не_галочка_остаётся_честным():
    """Колонка «Уведомление пользователю» ставит ✓ только по значению «да»,
    пустое значение даёт прочерк - правило матрицы не меняли."""
    правила = dict(t._МАТРИЦА_ПРАВИЛА)['Уведомление пользователю']

    assert ('да', '✓', None) in правила
    assert any(p[0] == 'нет' and p[1] == '✗' for p in правила)
    print('✓ правило матрицы прежнее: ✓ только по явному «Да»')
