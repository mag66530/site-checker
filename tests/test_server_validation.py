def test_ответ_302_редирект_addok_успешно():
    # Битрикс-вебформы (МПЭ «Заявка», «Нужна консультация»): успех = 302 с
    # formresult=addok в Location и ПУСТЫМ телом. Раньше падало в «ошибка»
    # (не 200, нет «спасибо» в теле) → ложное «сервер отклонил отправку»
    # при живом попапе «Спасибо».
    лок = ("https://mepen.ru/local/popups/form.php?WEB_FORM_ID=1"
           "&RESULT_ID=1356&formresult=addok&AJAX_CALL=Y")
    assert t._ответ_формы_вердикт("", 302, локация=лок) == "успешно"
    assert t._ответ_формы_вердикт("", 302, строгий=True, локация=лок) == "успешно"


