# -*- coding: utf-8 -*-
"""МТТ - ОДИН проект форм на все домены, включая Армению.

Сначала было заведено два проекта (mtt и mtt_am), потому что у Армении другой
интерфейс. Но домены и так выбираются городами, а формы разных интерфейсов
разводятся ключами движка «кроме_городов»/«только_города» - второй проект был
лишней сущностью в списке на странице.

Тест сторожит именно это: одна запись в списке проектов, все домены в cities.csv
и корректное ограничение блоков по городам. Иначе на каждом домене половина форм
уходила бы в «не найдена»: армянские селекторы на старом интерфейсе не находятся
и наоборот.
"""
import importlib.util
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ))

ПРОЕКТ = КОРЕНЬ / 'forms_tester' / 'projects' / 'mtt'


def _конфиг():
    spec = importlib.util.spec_from_file_location('cfg_mtt', ПРОЕКТ / 'config.py')
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def test_отдельного_проекта_армении_нет():
    assert not (КОРЕНЬ / 'forms_tester' / 'projects' / 'mtt_am').exists()
    import forms_run
    assert 'mtt_am' not in forms_run.PROJECT_NAMES
    assert 'mtt' in forms_run.PROJECT_NAMES


def test_армения_есть_в_городах():
    строки = (ПРОЕКТ / 'cities.csv').read_text(encoding='utf-8').splitlines()
    города = [s.split(',')[1] for s in строки[1:] if s.strip()]
    assert 'Ереван' in города
    assert 'Москва' in города
    # Все страны присутствия, чтобы домены выбирались галочками на странице.
    assert len(города) >= 8


def test_блоки_разведены_по_городам():
    cfg = _конфиг()
    армянские = [б for б in cfg.СТРАНИЦЫ_ДЛЯ_ПРОВЕРКИ
                 if б.get('только_города') == ['Ереван']]
    старые = [б for б in cfg.СТРАНИЦЫ_ДЛЯ_ПРОВЕРКИ
              if б.get('кроме_городов') == ['Ереван']]
    assert армянские and старые
    # Каждый блок ограничен ровно одним способом - иначе форма либо продублируется,
    # либо не попадёт ни в один город.
    for б in cfg.СТРАНИЦЫ_ДЛЯ_ПРОВЕРКИ:
        огр = bool(б.get('только_города')) + bool(б.get('кроме_городов'))
        assert огр == 1, б['тип']


def test_адреса_на_основном_домене():
    """forms_run подменяет домен под город (//met-trans.ru → //met-trans.am).
    Если адрес написан сразу на .am, подмена по городам работать не будет."""
    cfg = _конфиг()
    for тип, url in cfg.СТРАНИЦЫ.items():
        assert url.startswith('https://met-trans.ru'), (тип, url)


def test_армянский_телефон_литералом():
    """Маска Армении требует 10 цифр после +374, а константа ТЕЛЕФОН - для РФ.
    Значит в армянских блоках номер должен идти литералом."""
    cfg = _конфиг()
    for б in cfg.СТРАНИЦЫ_ДЛЯ_ПРОВЕРКИ:
        if б.get('только_города') != ['Ереван']:
            continue
        for сц in б['сценарии']:
            for шаг in сц['шаги']:
                поля = шаг.get('поля') or {}
                if 'phone' in поля:
                    assert поля['phone'].startswith('+374'), сц['название']
