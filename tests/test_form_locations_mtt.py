# -*- coding: utf-8 -*-
"""Подпись «Где находится» должна вести к форме, а не путать.

Поймано заказчиком: у формы «Оставить заявку (категория)» в отчёте стояло
«Кнопка в шапке сайта, открывает окно» - описание чужой формы СМУ, подтянутое
по общему словарю (там есть ключ «Оставить заявку», и он входит в наше
название). Для МТТ заведён свой словарь; тест держит две вещи: каждая форма
проекта описана, и описание не про шапку, если форма живёт в другом месте.
"""
import importlib.util
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / 'forms_tester'))

import form_locations as FL

КОНФИГ = КОРЕНЬ / 'forms_tester' / 'projects' / 'mtt' / 'config.py'


def _формы_проекта():
    spec = importlib.util.spec_from_file_location('cfg_mtt_loc', КОНФИГ)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    out = []
    for блок in m.СТРАНИЦЫ_ДЛЯ_ПРОВЕРКИ:
        for сц in блок['сценарии']:
            if сц.get('включено', True):
                out.append(сц['название'])
    return out


def test_у_каждой_формы_есть_своё_описание():
    свои = FL.FORM_WHERE_BY_PROJECT['mtt']
    for название in _формы_проекта():
        assert название in свои, f'нет описания для «{название}»'


def test_описание_не_врёт_про_шапку():
    """Про шапку пишем только у форм, которые реально открываются из шапки."""
    свои = FL.FORM_WHERE_BY_PROJECT['mtt']
    for название, где in свои.items():
        if 'шапк' in где.lower():
            assert ('шапк' in название.lower() or 'звонок' in название.lower()), \
                f'«{название}» описана как форма из шапки: {где}'


def test_чужое_описание_больше_не_подтягивается():
    """Раньше where() брала ключ «Оставить заявку» из общего словаря (СМУ)."""
    где = FL.where('Оставить заявку (категория)', 'mtt')
    assert 'категор' in где.lower()
    assert 'шапке сайта' not in где.lower()


def test_две_одноимённые_формы_описаны_по_разному():
    """«Оформление заказа» есть и у МТТ, и у других проектов - пути разные."""
    мтт = FL.where('Оформление заказа', 'mtt')
    смУ = FL.where('Оформление заказа', 'smu')
    assert мтт != смУ
    assert 'типоразмер' in мтт.lower() or 'галочк' in мтт.lower()
