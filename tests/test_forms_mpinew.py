"""Проверка форм на закрытом стенде (новый прод МПИ).

Два предмета проверки:
  • пароль сайта доезжает до браузера движка (без него все формы «не найдены»);
  • конфиг проекта цел: у каждой формы есть открывающий шаг, кнопка отправки и
    карта полей, а типы страниц и адреса не разъехались.
"""
import importlib.util
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / 'forms_tester'))

import site_auth


def _конфиг():
    путь = КОРЕНЬ / 'forms_tester' / 'projects' / 'mpinew' / 'config.py'
    spec = importlib.util.spec_from_file_location('cfg_mpinew', путь)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


# ── пароль сайта ─────────────────────────────────────────────────────

def test_без_пароля_ничего_не_меняется():
    """Обычные проекты (пароля в окружении нет) идут как раньше."""
    assert site_auth.вход_на_сайт({}) is None
    assert site_auth.вход_для_requests({}) is None
    assert site_auth.добавить_вход({'locale': 'ru-RU'}, {}) == {'locale': 'ru-RU'}
    print('✓ без пароля контекст браузера прежний')


def test_половина_пароля_не_считается():
    """Один логин без пароля - не вход: Playwright молча ушёл бы в 401."""
    assert site_auth.вход_на_сайт({'SITE_BASIC_LOGIN': 'admin'}) is None
    assert site_auth.вход_на_сайт({'SITE_BASIC_PASSWORD': 'p'}) is None
    print('✓ неполные данные игнорируются')


def test_пароль_доезжает_до_контекста():
    окружение = {'SITE_BASIC_LOGIN': 'admin', 'SITE_BASIC_PASSWORD': 'секрет'}

    kw = site_auth.добавить_вход({'locale': 'ru-RU'}, окружение)

    assert kw['http_credentials'] == {'username': 'admin', 'password': 'секрет'}
    assert site_auth.вход_для_requests(окружение) == ('admin', 'секрет')
    print('✓ логин/пароль уходят в браузер и в requests')


def test_движок_зовёт_вход_везде():
    """Все четыре точки, где движок открывает браузер, должны спрашивать пароль:
    прогон форм, cookie-плашка (2.12), мобильная вёрстка, админка."""
    for файл in ('test_all.py', 'privacy_check.py', 'mobile_check.py',
                 'admin_check.py', 'order_admin_check.py'):
        текст = (КОРЕНЬ / 'forms_tester' / файл).read_text(encoding='utf-8')
        assert 'site_auth' in текст, f'{файл}: вход на закрытый сайт не подключён'
        assert 'добавить_вход' in текст, f'{файл}: контекст создаётся без пароля'
    print('✓ пароль подключён во всех местах, где движок открывает браузер')


def test_страница_форм_знает_закрытый_проект():
    текст = (КОРЕНЬ / 'checklists' / 'forms_check.py').read_text(encoding='utf-8')

    assert "'mpinew'" in текст, 'проект не добавлен в список страницы'
    # Логин/пароль должны попасть в окружение дочернего процесса.
    assert 'SITE_BASIC_LOGIN' in текст and 'SITE_BASIC_PASSWORD' in текст
    assert '**_site_env' in текст, 'поля есть, но в запуск не передаются'
    print('✓ страница «Проверка форм» умеет пускать на закрытый сайт')


# ── конфиг проекта ───────────────────────────────────────────────────

def test_типы_страниц_и_адреса_совпадают():
    m = _конфиг()
    типы = {б['тип'] for б in m.СТРАНИЦЫ_ДЛЯ_ПРОВЕРКИ}

    assert типы == set(m.СТРАНИЦЫ), 'тип без адреса или адрес без типа'
    assert all(str(u).startswith('https://new.metpromintex.by')
               for u in m.СТРАНИЦЫ.values())
    print(f'✓ {len(типы)} типов страниц, все адреса - новый прод')


def test_все_формы_описаны_полностью():
    """У каждого шага «форма» есть контейнер, кнопка отправки и хотя бы одно поле."""
    m = _конфиг()
    форм = 0
    for блок in m.СТРАНИЦЫ_ДЛЯ_ПРОВЕРКИ:
        for сц in блок['сценарии']:
            шаги_форм = [ш for ш in сц['шаги'] if ш['действие'] == 'форма']
            assert len(шаги_форм) == 1, f'{сц["название"]}: форм в сценарии не одна'
            ш = шаги_форм[0]
            assert ш['css'] and ш['кнопка_css'], сц['название']
            assert ш['поля'], f'{сц["название"]}: карта полей пуста'
            форм += 1
    assert форм == 13, форм
    print(f'✓ все {форм} форм описаны полностью')


def test_модалки_открываются_кликом():
    """Форма внутри диалога недостижима без клика по кнопке - проверяем, что он есть."""
    m = _конфиг()
    for блок in m.СТРАНИЦЫ_ДЛЯ_ПРОВЕРКИ:
        for сц in блок['сценарии']:
            ш = [x for x in сц['шаги'] if x['действие'] == 'форма'][0]
            if 'role="dialog"' not in ш['css']:
                continue
            клики = [x for x in сц['шаги']
                     if x['действие'] == 'клик' and not x.get('необязательно')]
            assert клики, f'{сц["название"]}: модалку никто не открывает'
    print('✓ у каждой модалки есть свой открывающий клик')


