# -*- coding: utf-8 -*-
"""Непроверенная url-цель должна объяснять СВОЮ причину.

Из отчёта МПК (19.08.2026, лист КЗ): у пяти разных целей - «Контакты»,
«Корзина», два прайса - стоял ОДИН и тот же текст «Обычный прогон целей на неё
не попадает (заказ/оплата/«спасибо»). Включите галочку „Сначала прогнать формы“».

Две беды сразу: галочки такой на странице нет (формы гоняются сами, см.
goals_run), а причины у целей разные - файл не качаем, страницу заказа
подтверждает сквозной заказ, а обычной страницы просто не было в обходе.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import goals_tester as G


def _цель(номер, название, url_часть):
    return {'номер': номер, 'название': название, 'тип': 'url', 'условие': '',
            'идентификаторы': [], 'содержит': False, 'url_часть': url_часть}


def _разбор(цели, формы_прогнали=False, url_коды=None):
    G._результаты_форм = lambda pid: ({'x': 'ok'} if формы_прогнали else {})
    G._формные_цели = lambda pid: set()
    G._формные_url = lambda pid: set()
    каталог = {'проект': 'Тест', 'счётчик': '1', 'домен': 'https://site.ru',
               'цели': цели}
    прогон = {'fired': set(), 'привязки': set(), 'код': '', 'идентификаторы': set(),
              'url_коды': url_коды or {},
              'страницы': [{'название': 'Главная', 'url': 'https://site.ru/',
                            'код': 200, 'счётчик': True, 'визит': True}]}
    res = G._классифицировать('mpk', каталог, прогон)
    return {s['название']: s for s in res['строки']}


def test_несуществующая_галочка_ушла():
    строки = _разбор([_цель('1', 'Контакты', '/kontakti'),
                      _цель('2', 'Корзина', '/cart/cart'),
                      _цель('3', 'Прайс', 'metpromko-kz-price.xls')])
    for s in строки.values():
        assert 'Сначала прогнать формы' not in s['детали']


def test_у_разных_целей_разные_причины():
    строки = _разбор([_цель('1', 'Контакты', '/kontakti'),
                      _цель('2', 'Прайс', 'metpromko-kz-price.xls'),
                      _цель('3', 'Заказ оформлен', 'success')])
    тексты = {n: s['детали'] for n, s in строки.items()}
    assert len(set(тексты.values())) == 3, тексты
    assert 'файл' in тексты['Прайс']
    assert 'не было в обходе' in тексты['Контакты']
    assert 'заказ' in тексты['Заказ оформлен'].lower()


def test_страница_заказа_учитывает_гонялись_ли_формы():
    без = _разбор([_цель('3', 'Заказ оформлен', 'success')])
    с = _разбор([_цель('3', 'Заказ оформлен', 'success')], формы_прогнали=True)
    assert 'не гонялся' in без['Заказ оформлен']['детали']
    assert 'не дошёл' in с['Заказ оформлен']['детали']


def test_несуществующий_адрес_цели_это_проблема():
    """МПК Казахстан: цели ведут на /kontakti и /cart/cart, а сайт отдаёт 404 -
    такие цели не сработают никогда, это находка, а не «нет автопроверки»."""
    строки = _разбор([_цель('1', 'Контакты', '/kontakti'),
                      _цель('2', 'Корзина', '/cart/cart')],
                     url_коды={'/kontakti': 404, '/cart/cart': 404})
    for имя in ('Контакты', 'Корзина'):
        s = строки[имя]
        assert s['статус'] == 'Проблема', s
        assert 'нет (код 404)' in s['детали']


def test_живой_адрес_не_становится_проблемой():
    строки = _разбор([_цель('1', 'Контакты', '/kontakti')],
                     url_коды={'/kontakti': 200})
    assert строки['Контакты']['статус'] == 'Нет автопроверки'


def test_адреса_целей_проверяются_только_путями():
    """Подстрока «success» - не адрес, дёргать сайт по ней нельзя."""
    каталог = {'домен': 'https://site.ru', 'цели': [
        _цель('1', 'Заказ', 'success'), _цель('2', 'Контакты', '/kontakti')]}
    вызовы = []

    class _Ответ:
        status_code = 404

    import types
    fake = types.SimpleNamespace(
        get=lambda url, **kw: (вызовы.append(url), _Ответ())[1])
    sys.modules['requests'] = fake
    try:
        коды = G._проверить_адреса_url_целей('mpk', каталог)
    finally:
        del sys.modules['requests']
    assert коды == {'/kontakti': 404}
    assert вызовы == ['https://site.ru/kontakti']


def test_распознавание_файлов_и_страниц_успеха():
    for адрес in ('metpromko-kz-price.xls', 'catalog.pdf', 'prais-list.xlsx',
                  'gruzoperevozki-prais-list.xls'):
        assert G._ЦЕЛЬ_ФАЙЛ.search(адрес), адрес
    for адрес in ('success', '/thank-you', '/spasibo', '/order-complete'):
        assert G._ЦЕЛЬ_УСПЕХ.search(адрес), адрес
    # обычные страницы не должны попадать ни в одну из категорий
    for адрес in ('/kontakti', '/cart/cart', '/dostavka', '/articles'):
        assert not G._ЦЕЛЬ_ФАЙЛ.search(адрес), адрес
        assert not G._ЦЕЛЬ_УСПЕХ.search(адрес), адрес
