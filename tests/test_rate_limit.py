# ── Объединённый залп (двойная отправка + спам в одном заходе из 3 отправок) ──
def test_залп_все_три_прошли_лимита_нет():
    # 3 POST на адрес формы, блокировки не было → лимит не сработал.
    попытки = t._залп_в_попытки(mx=3, burst_блоки=[False, False])
    assert [p["успех"] for p in попытки] == [True, True, True]
    assert not any(p["блок"] for p in попытки)
    статус, _ = t.лимит_активно_вердикт(попытки)
    assert статус.startswith("Не сработала")


def test_залп_блок_на_втором_защита_сработала():
    # 1-я отправка прошла, на 2-й сервер показал блок → защита есть, попытка №2.
    попытки = t._залп_в_попытки(mx=1, burst_блоки=[True, False])
    assert попытки[1]["блок"] is True
    статус, деталь = t.лимит_активно_вердикт(попытки)
    assert статус == "Сработала защита" and "№2" in деталь


def test_залп_только_первая_прошла_блокирует_повтор():
    # Ушёл лишь 1 POST, текста блокировки нет (форма сама залочила кнопку) →
    # «Блокирует повтор» (клиентская защита от случайного дабл-клика).
    попытки = t._залп_в_попытки(mx=1, burst_блоки=[False])
    статус, _ = t.лимит_активно_вердикт(попытки)
    assert статус == "Блокирует повтор"


def test_залп_ни_одного_поста_проверить():
    # Форма вообще не отправилась (mx=0) → неоднозначно, честно «Проверить».
    попытки = t._залп_в_попытки(mx=0, burst_блоки=[])
    статус, _ = t.лимит_активно_вердикт(попытки)
    assert статус == "Проверить"


def test_залп_всегда_три_попытки():
    # Формат совпадает с прежней активной пробой: ровно _RATELIMIT_ПОПЫТОК строк.
    assert len(t._залп_в_попытки(mx=2, burst_блоки=[False, True])) == t._RATELIMIT_ПОПЫТОК


# ── Колонки в шапке лога ────────────────────────────────────────────────

