"""Стилизация полей: скругление сравниваем только там, где его ВИДНО.

Регресс ИМП (29.07.2026): на формах, где поля - подчёркивания (прозрачный фон,
рамка только снизу), тул писал ✗ «разнобой – поле 3 — скругление углов: нужно
4px — по факту 0px». Увидеть эту разницу невозможно: скруглять там нечего.
Скругление блока-контейнера (синяя карточка «Интересует вакансия?») тул не
проверяет вовсе - это отдельный элемент, а не поле формы.
"""
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "forms_tester"))

t = pytest.importorskip("test_all")

_БАЗА = {"font": "ProximaNova", "size": "14px", "color": "rgb(0, 0, 0)",
         "bw": "0px", "bs": "none", "bc": "rgb(0, 0, 0)",
         "pad": "12px 20px"}


def _поле(radius="4px", boxed=True, **kw):
    return {**_БАЗА, "radius": radius, "boxed": boxed, **kw}


class _FakeScope:
    """Заглушка формы: evaluate() отдаёт заранее снятые стили полей."""
    def __init__(self, поля, кнопка=None):
        self._r = {"поля": поля, "кнопка": кнопка}

    def evaluate(self, js, *a):
        return self._r


_КНОПКА = {**_БАЗА, "radius": "4px", "boxed": True, "bg": "rgb(230, 0, 60)"}


def test_радиус_без_видимой_коробки_не_сравнивается():
    # поле-подчёркивание: фон прозрачный, рамки по кругу нет → radius не виден
    assert t._радиус_для_сверки(_поле("0px", boxed=False)) == \
        t._радиус_для_сверки(_поле("4px", boxed=False))


def test_радиус_у_поля_с_коробкой_сравнивается_как_раньше():
    assert t._радиус_для_сверки(_поле("4px")) != t._радиус_для_сверки(_поле("0px"))


def test_подчёркивания_с_разным_радиусом_это_не_разнобой():
    # Ровно случай ИМП: 2 поля с radius 4px и одно с 0px, у всех - ни фона, ни
    # рамки по кругу. Раньше = ✗ «разнобой», теперь = ✓ «консистентно».
    поля = [_поле("4px", boxed=False, bg="rgba(0, 0, 0, 0)"),
            _поле("4px", boxed=False, bg="rgba(0, 0, 0, 0)"),
            _поле("0px", boxed=False, bg="rgba(0, 0, 0, 0)")]
    r = t.стиль_формы(_FakeScope(поля, _КНОПКА))
    assert r["состояние"] == "консистентно", r["детали"]


def test_реальный_разнобой_по_радиусу_остаётся_дефектом():
    # У полей есть коробка (фон/рамка) - разный радиус виден глазом, это дефект.
    поля = [_поле("4px", bg="rgb(228, 228, 228)"),
            _поле("4px", bg="rgb(228, 228, 228)"),
            _поле("0px", bg="rgb(228, 228, 228)")]
    r = t.стиль_формы(_FakeScope(поля, _КНОПКА))
    assert r["состояние"] == "разнобой"
    assert "скругление углов" in r["детали"]


def test_разнобой_по_шрифту_ловится_и_у_подчёркиваний():
    # Скругление игнорируем, но остальные свойства - нет.
    поля = [_поле("0px", boxed=False, bg="rgba(0, 0, 0, 0)"),
            _поле("0px", boxed=False, bg="rgba(0, 0, 0, 0)", size="18px")]
    r = t.стиль_формы(_FakeScope(поля, _КНОПКА))
    assert r["состояние"] == "разнобой"
    assert "размер шрифта" in r["детали"]
