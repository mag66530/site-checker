# ── 3. сайт срезал ресурсы ───────────────────────────────────────────

class _Стр:
    """Страница-заглушка: отдаёт готовый замер Performance API."""

    def __init__(self, всего, коды):
        self.данные = {'всего': всего, 'плохих': sum(коды.values()), 'коды': коды}

    def evaluate(self, js, *a):
        return self.данные


def test_массовые_429_это_ограничение_доступа():
    """Замер снят с живого metpromko.by: 46 из 81 ресурса с кодом 429."""
    текст = t.сайт_срезал_ресурсы(_Стр(81, {429: 46}))

    assert текст
    assert '429' in текст and '46' in текст
    assert 'не дефект формы' in текст
    print('✓ 429 на пачке ресурсов описывается как ограничение доступа')


def test_одна_битая_картинка_не_повод():
    """У живого metpromko.ru таких ресурсов 0, а единичные 404 бывают у всех -
    обвинять сайт из-за одной картинки нельзя."""
    assert t.сайт_срезал_ресурсы(_Стр(83, {})) == ''
    assert t.сайт_срезал_ресурсы(_Стр(83, {404: 2})) == ''
    print('✓ единичные битые ресурсы вердикт не меняют')


def test_сломанный_замер_не_ломает_прогон():
    class Падает:
        def evaluate(self, js, *a):
            raise RuntimeError('нет performance')

    assert t.сайт_срезал_ресурсы(Падает()) == ''
    print('✓ недоступный Performance API просто ничего не сообщает')


def test_не_проверено_даёт_предупреждение_а_не_крест():
    """Статус «НЕ ПРОВЕРЕНО …» должен читаться как ⚠ «Не проверено», иначе
    ограничение доступа снова выглядело бы дефектом сайта."""
    коротко, деталь = t._status_clean_reason(
        'НЕ ПРОВЕРЕНО (сайт не отдал 46 из 81 ресурсов страницы 429)')

    assert коротко == 'Не проверено'
    assert '429' in деталь
    правила = dict(t._МАТРИЦА_ПРАВИЛА)['Статус']
    assert ('не проверено', '⚠', None) not in правила      # у него свой текст
    assert any(p[0] == 'не проверено' and p[1] == '⚠' for p in правила)
    print('✓ «Не проверено» — предупреждение, а не ✗')
