# -*- coding: utf-8 -*-
"""Теги-артефакты форматирования в подзаголовках, шапке и подвале.

Пункт чек-листа «Верстка»: <strong>/<b>/<em> не должно быть там, где жирность и
курсив задаются стилями. Отдельной проверки в проекте не было.

Главная опасность правила - ложные срабатывания на ИКОНКАХ: <i class="fa-…">
это значок, а не форматирование текста. На главной МПЭ таких в шапке 549 штук -
без исключения проверка утонула бы в шуме и её пришлось бы выключить.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import layout_checker as L


def test_подзаголовки_ловятся():
    html = '<h2>Каталог <strong>металлопроката</strong></h2>'
    r = L.проверить_артефакты(html)
    assert r['всего'] == 1
    a = r['примеры'][0]
    assert a['тег'] == 'strong' and a['зона'] == 'подзаголовок h2'
    assert a['текст'] == 'металлопроката'


def test_шапка_и_подвал():
    html = ('<header><a href="/catalog"><b>Каталог</b></a></header>'
            '<footer><em>Все права защищены</em></footer>'
            '<nav><b>Доставка</b></nav>')
    r = L.проверить_артефакты(html)
    assert r['всего'] == 3
    assert r['по_зонам'] == {'шапка/меню': 2, 'подвал': 1}


def test_иконки_не_считаются():
    """<i> без текста или с иконочным классом - значок, а не артефакт."""
    html = ('<header>'
            '<i class="fa fa-phone"></i>'
            '<i class="icon-cart"></i>'
            '<i class="material-icons">menu</i>'
            '<i></i>'
            '</header>')
    assert L.проверить_артефакты(html)['всего'] == 0


def test_i_с_текстом_считается():
    """Курсив текста тегом - это артефакт, даже если тег тот же <i>."""
    html = '<h3>Доставка <i>по всей России</i></h3>'
    r = L.проверить_артефакты(html)
    assert r['всего'] == 1 and r['примеры'][0]['тег'] == 'i'


def test_основной_текст_страницы_не_трогаем():
    """В контенте <strong> уместен - правило только про заголовки, шапку и подвал."""
    html = ('<main><p>Сталь <strong>ГОСТ 380-2005</strong> в наличии</p>'
            '<h1>Металлопрокат <b>в Москве</b></h1></main>')
    assert L.проверить_артефакты(html)['всего'] == 0


def test_h1_не_дублируем():
    """Чистота H1 проверяется отдельно (meta_checker), иначе одна находка
    попадала бы в отчёт дважды."""
    assert L.проверить_артефакты('<h1><b>Заголовок</b></h1>')['всего'] == 0
    import meta_checker
    assert meta_checker._h1_has_inner_markup('<b>Заголовок</b>') is True


def test_пустой_тег_не_находка():
    assert L.проверить_артефакты('<h2><strong> </strong>Каталог</h2>')['всего'] == 0


def test_попадает_в_предупреждения_вёрстки():
    """Замечание, а не ошибка: сайт от этого не ломается."""
    html = ('<html><head><meta name="viewport" content="width=device-width">'
            '</head><body><header><b>Каталог</b></header></body></html>')
    r = L.check_layout(html, [], base_url='https://site.ru/')
    assert r['artifacts']['всего'] == 1
    текст = ' '.join(r['warnings'])
    assert 'теги-артефакты' in текст and 'шапка/меню - 1' in текст
    assert not [i for i in r['issues'] if 'артефакт' in i]


def test_находка_доходит_до_плана_работ():
    """Текст предупреждения должен попадать в своё правило, а не в заглушку
    «требует ручной проверки»."""
    import report_priorities as RP
    f = RP.Finding('Предупреждение', 'Вёрстка',
                   'теги-артефакты форматирования: 506 (шапка/меню - 506). '
                   'Например: <b> «Каталог»',
                   'Москва', 'Главная', 'https://site.ru/')
    задача = RP.classify(f)
    assert задача['task_group'] == 'layout_artifacts'
    assert задача['why'] != RP._DEFAULT['why']


def test_правило_отчёта_есть():
    """Без правила находка ушла бы в «требует ручной проверки»."""
    import report_priorities as RP
    правила = [r for r in RP._RULES if r[1] == 'теги-артефакты']
    assert правила, 'нет правила для артефактов'
    раздел, _, приоритет, _, ключ, заголовок, почему = правила[0]
    assert раздел == 'Вёрстка' and ключ == 'layout_artifacts'
    assert 'подзаголовк' in заголовок.lower()
    assert почему
