# -*- coding: utf-8 -*-
"""Две находки проверки КП на МТТ.

1. Армения (+374). Номер Еревана в КП - «37 (443) 154598», РОВНО те же цифры
   стоят и на met-trans.am. Но код 374 не был известен: номер обрезался до
   последних десяти цифр и показывался как российский «+7 (744) 315-45-98»,
   поэтому «Общий Город» уходил в расхождение на ровном месте.

2. Двойное имя города. В КП «Нур-Султан (Астана)», сайт ns.mtt.kz пишет
   «Астана». Проверка искала строку целиком и писала «город из КП на сайте не
   найден», хотя город выведен.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import kp
import variables_run as V


# ── Телефоны Армении ─────────────────────────────────────────────────


def test_армянский_номер_не_становится_российским():
    """37443154598 - это +374 43 154598, а не +7 744 315 45 98."""
    assert kp.normalize_phone('37 (443) 154598') == '43154598'
    assert kp.normalize_phone('+374 43 154598') == '43154598'
    assert kp.normalize_phone('374-43-15-45-98') == '43154598'


def test_номер_с_сайта_и_из_кп_сходятся():
    """На met-trans.am номер записан ровно как в КП - сверка обязана сойтись."""
    из_кп = kp.normalize_phone('37 (443) 154598')
    с_сайта = kp.split_phones('tel:37 (443) 154598')
    assert из_кп in с_сайта, с_сайта


def test_номер_достаётся_из_ячейки_кп():
    """Ячейка КП разбирается своим путём (phones_in_cell). Пока нижней границей
    было 9 цифр, армянский номер из неё не доставался вовсе: сверка получала
    пустой список и писала расхождение при совпадающих номерах."""
    assert kp.phones_in_cell('37 (443) 154598') == ['43154598']
    # соседние страны не задеты
    assert kp.phones_in_cell('+375 (44) 766-62-58') == ['447666258']
    assert kp.phones_in_cell('(495) 799-14-38') == ['4957991438']


def test_показ_армянского_номера_читаемый():
    assert kp._fmt('43154598', '374') == '+374 (43) 15-45-98'


def test_код_страны_по_домену_и_стране():
    class _R:
        country = 'Армения'
        domain = 'met-trans.am'
    assert kp._dial_for(_R()) == '374'

    class _R2:
        country = ''
        domain = 'met-trans.am'
    assert kp._dial_for(_R2()) == '374'


def test_другие_страны_не_поехали():
    """Соседние коды не должны пострадать от нового правила."""
    assert kp.normalize_phone('+375 (44) 766-62-58') == '447666258'
    assert kp.normalize_phone('+996 221 31 88 82') == '221318882'
    assert kp.normalize_phone('+7 (495) 799-14-38') == '4957991438'
    assert kp.normalize_phone('8 (4852) 66-29-46') == '4852662946'


# ── Двойное имя города ───────────────────────────────────────────────


def test_варианты_двойного_имени():
    assert V._варианты_города('Нур-Султан (Астана)') == ['Нур-Султан', 'Астана']
    assert V._варианты_города('Москва') == ['Москва']
    assert V._варианты_города('') == []


def test_город_находится_по_любому_из_имён():
    rx = V._own_city_regex('Нур-Султан (Астана)')
    assert rx.search('Главная Мет-Транс Астана и Акмолинская область')
    assert rx.search('Металлопрокат в Нур-Султане')
    assert not rx.search('Металлопрокат в Караганде')


def test_обычные_города_ищутся_как_раньше():
    """Правка не должна трогать склонения обычных названий."""
    assert V._own_city_regex('Тула').search('Металлобаза в Туле')
    assert V._own_city_regex('Череповец').search('доставка по Череповцу')
    assert V._own_city_regex('Новый Уренгой').search('склад в Новом Уренгое')
    assert not V._own_city_regex('Казань').search('Металлопрокат в Самаре')
