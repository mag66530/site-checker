# ── вычленение ключа ────────────────────────────────────────────────

def test_ключ_без_коммерческих_хвостов_и_города():
    ключ = tko.ключ_из_title('Профиль стоечный: купить в Москве | цена в Steelborg',
                             city='Москва')
    assert ключ == ['профиль', 'стоечный']


def test_ключ_из_примера_инструкции():
    assert tko.ключ_из_title('Труба бесшовная купить') == ['труба', 'бесшовная']
    assert tko.ключ_из_title('Купить алюминиевый лист по ценам') == [
        'алюминиевый', 'лист']


def test_город_в_предложном_падеже_не_попадает_в_ключ():
    ключ = tko.ключ_из_title('Арматура рифлёная — купить в Нижнем Новгороде',
                             city='Нижний Новгород')
    assert ключ == ['арматура', 'рифленая']


def test_размеры_и_единицы_в_ключ_не_идут():
    """«труба нержавеющая мм» никто не ищет - у всех перестановок ноль, и
    проверка порядка теряет смысл. Типоразмер из ключа выкидываем."""
    assert tko.ключ_из_title('Труба 57 мм цена') == ['труба']
    assert tko.ключ_из_title('Труба нержавеющая 24 мм купить') == [
        'труба', 'нержавеющая']
    assert tko.ключ_из_title('Уплотнитель резиновый 3х10 мм') == [
        'уплотнитель', 'резиновый']


def test_нулевая_частотность_это_не_ок():
    ч = {'заглушка литая': {'уточнённая': 0}, 'литая заглушка': {'уточнённая': 0}}
    r = tko.вердикт(['заглушка', 'литая'], ч)
    assert r['status'] == 'skip' and 'частотность 0' in r['detail']


def test_микрочастотность_не_даёт_вердикта():
    """4 против 6 показов - это шум, а не «перепиши title»."""
    ч = _част({'канат крановый': 4, 'крановый канат': 6})
    assert tko.вердикт(['канат', 'крановый'], ч)['status'] == 'skip'


def test_фразовая_частотность_в_вердикт_не_идёт():
    """Фразовая одинакова у всех перестановок - опираться на неё нельзя."""
    ч = {'труба бесшовная': {'фразовая': 856}, 'бесшовная труба': {'фразовая': 856}}
    assert tko.вердикт(['бесшовная', 'труба'], ч)['status'] == 'skip'


def test_второй_ключ_после_запятой_не_берём():
    """«Сизалевый канат, сизалевая верёвка» - в title ключ первый, остальное
    хвост; без этого в Вордстат уходила фраза из четырёх слов с нулём."""
    assert tko.ключ_из_title('Сизалевый канат, сизалевая верёвка купить') == [
        'сизалевый', 'канат']


def test_чужой_город_из_списка_проекта_режется():
    """У СМУ московская категория подписана «цена в Екатеринбурге»."""
    ключ = tko.ключ_из_title('Полоса нержавеющая купить оптом, цена в Екатеринбурге',
                             city='Москва', города=['Москва', 'Екатеринбург'])
    assert ключ == ['полоса', 'нержавеющая']


def test_однословный_ключ_проверять_нечего():
    assert tko.варианты_порядка(tko.ключ_из_title('Арматура купить')) == []


