# ── вердикт ─────────────────────────────────────────────────────────

def _част(пары):
    return {f.lower(): {'уточнённая': n} for f, n in пары.items()}


def test_самый_частотный_порядок_в_title_это_ок():
    ч = _част({'труба бесшовная': 1200, 'бесшовная труба': 300})
    r = tko.вердикт(['труба', 'бесшовная'], ч)
    assert r['status'] == 'ok' and r['лучший'] == 'труба бесшовная'


def test_редкий_порядок_в_title_это_находка():
    ч = _част({'бесшовная труба': 300, 'труба бесшовная': 1200})
    r = tko.вердикт(['бесшовная', 'труба'], ч)
    assert r['status'] == 'bad'
    assert r['лучший'] == 'труба бесшовная' and r['свой_вес'] == 300
    assert 'чаще ищут' in r['detail']


def test_почти_равные_частотности_не_находка():
    """Вордстат шумит: отрыв в пределах порога - не повод переписывать title."""
    ч = _част({'лист алюминиевый': 1000, 'алюминиевый лист': 1100})
    assert tko.вердикт(['лист', 'алюминиевый'], ч)['status'] == 'ok'


def test_без_данных_частотности_пропуск_а_не_ошибка():
    r = tko.вердикт(['труба', 'бесшовная'], {})
    assert r['status'] == 'skip'


def test_фолбэк_на_точную_частотность():
    ч = {'труба бесшовная': {'точная': 900},
         'бесшовная труба': {'точная': 100}}
    r = tko.вердикт(['труба', 'бесшовная'], ч)
    assert r['status'] == 'ok' and r['тип'] == 'точная'


# ── разбор ответа API ───────────────────────────────────────────────

def test_разбор_живого_ответа_вордстата():
    """Формат сверен с боевым ответом 21.08.2026: фразы - КЛЮЧИ словаря,
    значение - список из одной записи. Порядок слов меняет только exact."""
    ответ = {'code': 'TASK_RESULT', 'result': {'type': 1, 'data': {
        'regions': ['Весь мир'],
        'result': {
            'труба бесшовная': [{'base': 48566, 'quoted': 856,
                                 'overal': 575, 'exact': 371}],
            'бесшовная труба': [{'base': 48566, 'quoted': 856,
                                 'overal': 575, 'exact': 204}],
        }}}}
    ч = wa.parse_frequencies(ответ)
    assert ч['труба бесшовная']['уточнённая'] == 371
    assert ч['бесшовная труба']['уточнённая'] == 204
    assert ч['труба бесшовная']['точная'] == 575
    assert ч['труба бесшовная']['базовая'] == 48566
    # и вердикт на этих числах - порядок в title верный
    assert tko.вердикт(['труба', 'бесшовная'], ч)['status'] == 'ok'
    assert tko.вердикт(['бесшовная', 'труба'], ч)['status'] == 'bad'


def test_разбор_записи_с_полем_query():
    ответ = {'data': [{'query': 'лист алюминиевый', 'exact': '1 400'}]}
    assert wa.parse_frequencies(ответ)['лист алюминиевый']['уточнённая'] == 1400


# ── страницы прогона ────────────────────────────────────────────────

class _Строка:
    def __init__(self, url, city='Москва', type_code='category', is_ok=True,
                 title=None):
        self.url, self.city, self.type_code, self.is_ok = url, city, type_code, is_ok
        self.meta = {'title': title} if title else None


def test_страницы_берём_только_категории_с_ключом():
    res = [_Строка('https://s.ru/catalog/truba/', title='Труба бесшовная купить'),
           _Строка('https://s.ru/product/x/', type_code='product',
                   title='Труба бесшовная 57 мм'),
           _Строка('https://s.ru/catalog/armatura/', title='Арматура купить')]
    стр = tko.страницы_из_результатов(res)
    assert [p['url'] for p in стр] == ['https://s.ru/catalog/truba/']


def test_title_дочитанный_отдельно_подхватывается():
    """Галочка «Метаданные» выключена - r.meta пуст, title приходит добором."""
    res = [_Строка('https://s.ru/catalog/truba/')]
    assert tko.страницы_из_результатов(res) == []
    assert tko.адреса_без_title(res) == ['https://s.ru/catalog/truba/']
    стр = tko.страницы_из_результатов(
        res, ('category',), (),
        {'https://s.ru/catalog/truba/': 'Труба бесшовная купить в Москве'})
    assert стр and стр[0]['ключ'] == ['труба', 'бесшовная']
