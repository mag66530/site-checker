"""XSS-проба: когда проверить не вышло - в отчёте должна быть ПРИЧИНА.

Запрос заказчика по отчёту ИМП: в матрице стояло голое «XSS не проверен», и
было непонятно ни что случилось, ни что делать дальше. Теперь вердикт несёт
человеческое объяснение: что за вторая заявка, почему она не ушла и как
проверить руками.
"""
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "forms_tester"))

t = pytest.importorskip("test_all")


def test_не_отправилась_даёт_понятную_инструкцию_на_руки():
    ст, дет = t.xss_вердикт(отправлена=False, исполнился=False, сырой=False)
    assert ст == "Проверить"
    # Текст должен быть понятен без знания внутренней кухни тула: что случилось
    # и что человеку сделать руками (прошлая формулировка про «ВТОРУЮ заявку с
    # безвредной тест-строкой» заказчику не сказала ничего).
    assert "xss не проверен" in дет.lower()
    assert "<b>тест</b>" in дет
    assert "жирным" in дет


def test_причина_попадает_в_текст():
    ст, дет = t.xss_вердикт(
        False, False, False,
        причина="поле «name» сайт считает заполненным неверно")
    assert ст == "Проверить"
    assert "поле «name»" in дет


def test_рабочие_исходы_не_изменились():
    assert t.xss_вердикт(True, True, False)[0] == "УЯЗВИМА"
    assert t.xss_вердикт(True, False, True)[0] == "УЯЗВИМА"
    assert t.xss_вердикт(True, False, False)[0] == "Защищена"


def test_причина_не_подмешивается_в_успешные_исходы():
    _, дет = t.xss_вердикт(True, False, False, причина="что-то пошло не так")
    assert "что-то пошло не так" not in дет
