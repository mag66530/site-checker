"""
mem_usage.py - сколько памяти съел контейнер прямо сейчас.

Зачем: тяжёлые прогоны (проверка форм - реальный Chromium на каждый поток)
живут в одном контейнере с самим приложением. Когда контейнер выходит за
лимит, его убивают целиком - приложение падает с «Oh no», а в логе ни строчки:
процесс не падал, его прибили. Понять постфактум нечего, поэтому пишем расход
ПО ХОДУ прогона - страница тайлит лог вживую, и потолок видно до падения.

Читаем cgroup - именно он отражает лимит КОНТЕЙНЕРА, а не хоста:
  • cgroup v2: /sys/fs/cgroup/memory.current и memory.max;
  • cgroup v1: /sys/fs/cgroup/memory/memory.usage_in_bytes и .limit_in_bytes.
Локально (Windows/Mac) файлов нет - функция возвращает пусто, и строка в лог
просто не пишется.
"""
from __future__ import annotations

from pathlib import Path

# «Лимита нет» cgroup обозначает словом max (v2) или огромным числом (v1).
_БЕЗ_ЛИМИТА = 1 << 62

_V2_ИСПОЛЬЗОВАНО = 'sys/fs/cgroup/memory.current'
_V2_ЛИМИТ = 'sys/fs/cgroup/memory.max'
_V1_ИСПОЛЬЗОВАНО = 'sys/fs/cgroup/memory/memory.usage_in_bytes'
_V1_ЛИМИТ = 'sys/fs/cgroup/memory/memory.limit_in_bytes'


def _число(корень: Path, отн: str):
    """Целое из файла cgroup; None - файла нет, пусто или «max»."""
    try:
        текст = (корень / отн).read_text(encoding='utf-8').strip()
    except Exception:  # noqa: BLE001
        return None
    if not текст or текст == 'max':
        return None
    try:
        знач = int(текст.split()[0])
    except (ValueError, IndexError):
        return None
    return None if знач >= _БЕЗ_ЛИМИТА else знач


def использование(корень='/') -> tuple:
    """(занято_байт, лимит_байт). Любой элемент может быть None."""
    к = Path(корень)
    занято = _число(к, _V2_ИСПОЛЬЗОВАНО)
    лимит = _число(к, _V2_ЛИМИТ)
    if занято is None:
        занято = _число(к, _V1_ИСПОЛЬЗОВАНО)
    if лимит is None:
        лимит = _число(к, _V1_ЛИМИТ)
    return занято, лимит


def _мб(байт) -> int:
    return int(round(байт / (1024 * 1024)))


def строка(корень='/') -> str:
    """Готовая строка для лога или '' - если мерить нечем (локальный запуск).

    Примеры:
        'Память контейнера: 512 МБ из 1024 МБ (50%)'
        'Память контейнера: 512 МБ (лимит не задан)'
    """
    занято, лимит = использование(корень)
    if занято is None:
        return ''
    if not лимит:
        return f'Память контейнера: {_мб(занято)} МБ (лимит не задан)'
    процент = int(round(занято * 100 / лимит))
    хвост = '  ⚠ близко к пределу' if процент >= 85 else ''
    return (f'Память контейнера: {_мб(занято)} МБ из {_мб(лимит)} МБ '
            f'({процент}%){хвост}')
