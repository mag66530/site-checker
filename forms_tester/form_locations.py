def where(название: str, проект: str = '') -> str:
    """Подсказка «где находится форма» по её названию. Если известен проект -
    сначала смотрим его собственный словарь (там живут названия, которые у
    разных проектов означают разные формы). Терпима к обрамлению: строки-
    названия в отчёте иногда приходят с пробелами/суффиксом города - сначала
    пробуем точное совпадение, потом по «голому» началу названия."""
    if not название:
        return ''
    имя = str(название).strip()
    свои = FORM_WHERE_BY_PROJECT.get(str(проект).strip()) or {}
    if имя in свои:
        return свои[имя]
    if имя in FORM_WHERE:
        return FORM_WHERE[имя]
    for ключ in sorted(свои, key=len, reverse=True):
        if ключ and ключ in имя:
            return свои[ключ]
    # Иногда к названию приклеен суффикс/префикс (город, пометка) - ищем ключ,
    # который целиком содержится в названии (самый длинный - точнее).
    for ключ in sorted(FORM_WHERE, key=len, reverse=True):
        if ключ and ключ in имя:
            return FORM_WHERE[ключ]
    return ''
