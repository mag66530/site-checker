"""Вход на закрытый паролем сайт (nginx Basic auth) для проверки форм.

Зачем: новый прод МПИ (new.metpromintex.by) отдаёт 401 на ВСЁ, пока браузер не
покажет логин/пароль. Без этого проверка форм видела только окно авторизации.

Логин и пароль движок берёт из окружения (их кладёт страница «Проверка форм» из
полей проекта), а не из config.py: в git пароль попадать не должен.

Playwright сам решает, кому показывать пароль: http_credentials он отправляет
ТОЛЬКО в ответ на 401 от сайта - на чужие домены (Метрика, шрифты) заголовок не
уходит. Поэтому здесь, в отличие от http_checker, отдельная фильтрация по хосту
не нужна.
"""
import os

ЛОГИН_ENV = "SITE_BASIC_LOGIN"
ПАРОЛЬ_ENV = "SITE_BASIC_PASSWORD"


def вход_на_сайт(окружение=None):
    """{'username': …, 'password': …} для new_context(http_credentials=…) или
    None, если пароль не задан (обычные проекты - как раньше)."""
    env = окружение if окружение is not None else os.environ
    логин = (env.get(ЛОГИН_ENV) or "").strip()
    пароль = env.get(ПАРОЛЬ_ENV) or ""
    if not логин or not пароль:
        return None
    return {"username": логин, "password": пароль}


def добавить_вход(ctx_kw: dict, окружение=None) -> dict:
    """Дописывает http_credentials в аргументы new_context, если пароль задан.
    Возвращает тот же словарь - удобно звать прямо в вызове."""
    вход = вход_на_сайт(окружение)
    if вход:
        ctx_kw["http_credentials"] = вход
    return ctx_kw


def вход_для_requests(окружение=None):
    """(логин, пароль) для requests(auth=…) или None. Нужен там, где движок
    качает страницу без браузера."""
    вход = вход_на_сайт(окружение)
    if not вход:
        return None
    return (вход["username"], вход["password"])
