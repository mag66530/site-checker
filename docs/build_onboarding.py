# -*- coding: utf-8 -*-
"""Два простых файла для подключения новых проектов:
   1) «Что собрать по проекту» — чек-лист для проектов (без тех-деталей);
   2) «Доступы — для меня» — шпаргалка по ключам/токенам.
Оформление берётся из преамбулы build_guide.py (единый стиль)."""
import os

_here = os.path.dirname(os.path.abspath(__file__))
_preamble = open(os.path.join(_here, 'build_guide.py'), encoding='utf-8').read().split('#  ТИТУЛ')[0]

KP_LINK = "https://docs.google.com/spreadsheets/d/19DOfoWJmCG4_MbHkPH2xFCo4GWs9v2eDxvFrBYTnteQ/edit"
FORMS_LINK = "https://docs.google.com/spreadsheets/d/1Tdh9GRw6xxIfG2XGhktzweA8NjRVe7-miuIeEWWeXEo/edit"


def fresh():
    ns = {}
    exec(compile(_preamble, 'preamble', 'exec'), ns)
    return ns


def hyperlink(ns, paragraph, url, text):
    OxmlElement, qn = ns['OxmlElement'], ns['qn']
    part = paragraph.part
    r_id = part.relate_to(
        url, 'http://schemas.openxmlformats.org/officeDocument/2006/relationships/hyperlink',
        is_external=True)
    h = OxmlElement('w:hyperlink'); h.set(qn('r:id'), r_id)
    run = OxmlElement('w:r'); rpr = OxmlElement('w:rPr')
    col = OxmlElement('w:color'); col.set(qn('w:val'), '0563C1'); rpr.append(col)
    u = OxmlElement('w:u'); u.set(qn('w:val'), 'single'); rpr.append(u)
    run.append(rpr)
    t = OxmlElement('w:t'); t.text = text; run.append(t)
    h.append(run); paragraph._p.append(h)


