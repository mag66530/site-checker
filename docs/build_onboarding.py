pagebreak = ns['pagebreak']
NEW_FILL = ns['NEW_FILL']


def hyperlink(paragraph, url, text):
    OxmlElement, qn = ns['OxmlElement'], ns['qn']
    r_id = paragraph.part.relate_to(
        url, 'http://schemas.openxmlformats.org/officeDocument/2006/relationships/hyperlink',
        is_external=True)
    h = OxmlElement('w:hyperlink'); h.set(qn('r:id'), r_id)
    run = OxmlElement('w:r'); rpr = OxmlElement('w:rPr')
    col = OxmlElement('w:color'); col.set(qn('w:val'), '0563C1'); rpr.append(col)
    u = OxmlElement('w:u'); u.set(qn('w:val'), 'single'); rpr.append(u)
    run.append(rpr)
    t = OxmlElement('w:t'); t.text = text; run.append(t)
    h.append(run); paragraph._p.append(h)


