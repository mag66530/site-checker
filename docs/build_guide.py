def _ln(tag):
    return tag.split('}')[-1]

def _insert_ordered(parent, child, order):
    idx = order.index(_ln(child.tag))
    for existing in list(parent):
        ln = _ln(existing.tag)
        if ln in order and order.index(ln) > idx:
            existing.addprevious(child)
            return
    parent.append(child)

def _set_shading(el, fill):
    """Вставляет w:shd в правильной по схеме OOXML позиции (pPr или tcPr)."""
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear'); shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), fill)
    order = _TCPR_ORDER if _ln(el.tag) == 'tcPr' else _PPR_ORDER
    _insert_ordered(el, shd, order)

