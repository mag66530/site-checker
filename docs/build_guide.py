def para(runs, style=None, after=6):
    """runs: str или список (текст, bold, italic, color)."""
    p = doc.add_paragraph(style=style)
    p.paragraph_format.space_after = Pt(after)
    if isinstance(runs, str):
        runs = [(runs,)]
    for r in runs:
        txt = r[0]; bold = r[1] if len(r) > 1 else False
        ital = r[2] if len(r) > 2 else False
        col = r[3] if len(r) > 3 else None
        run = p.add_run(txt); run.bold = bold; run.italic = ital
        if col: run.font.color.rgb = col
    return p

def bullet(runs, level=0):
    p = doc.add_paragraph(style='List Bullet' if level == 0 else 'List Bullet 2')
    p.paragraph_format.space_after = Pt(3)
    if isinstance(runs, str):
        runs = [(runs,)]
    for r in runs:
        txt = r[0]; bold = r[1] if len(r) > 1 else False
        ital = r[2] if len(r) > 2 else False
        run = p.add_run(txt); run.bold = bold; run.italic = ital
    return p

def callout(icon, text, fill):
    """Плашка-выноска в один абзац с фоновой заливкой."""
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(4); p.paragraph_format.space_after = Pt(8)
    p.paragraph_format.left_indent = Cm(0.25); p.paragraph_format.right_indent = Cm(0.25)
    ppr = p._p.get_or_add_pPr()
    _set_shading(ppr, fill)
    # рамка-паддинг сверху/снизу
    spacing = ppr.find(qn('w:spacing'))
    r0 = p.add_run(icon + '  '); r0.bold = True
    if isinstance(text, str):
        text = [(text,)]
    for r in text:
        txt = r[0]; bold = r[1] if len(r) > 1 else False
        run = p.add_run(txt); run.bold = bold
    return p

def tip(text):  return callout('💡', text, TIP_FILL)
def warn(text): return callout('⚠', text, WARN_FILL)

def check(title, what, where=None):
    """Описание одной проверки: жирный заголовок + текст + где в отчёте."""
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(5)
    p.paragraph_format.left_indent = Cm(0.4)
    p.paragraph_format.first_line_indent = Cm(-0.4)
    r = p.add_run(title); r.bold = True
    p.add_run(' — ' + what)
    if where:
        p.add_run('  ')
        w = p.add_run('Где в отчёте: ' + where + '.'); w.italic = True; w.font.color.rgb = MUTED
    return p

def table(headers, rows, widths=None, zebra=True):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    hdr = t.rows[0].cells
    for i, htext in enumerate(headers):
        cell = hdr[i]
        _set_shading(cell._tc.get_or_add_tcPr(), HEADER_FILL)
        cp = cell.paragraphs[0]; cp.paragraph_format.space_after = Pt(2); cp.paragraph_format.space_before = Pt(2)
        run = cp.add_run(htext); run.bold = True; run.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF); run.font.size = Pt(10)
    for ri, row in enumerate(rows):
        cells = t.add_row().cells
        for ci, val in enumerate(row):
            cell = cells[ci]
            if zebra and ri % 2 == 1:
                _set_shading(cell._tc.get_or_add_tcPr(), ZEBRA_FILL)
            cp = cell.paragraphs[0]; cp.paragraph_format.space_after = Pt(2); cp.paragraph_format.space_before = Pt(2)
            # поддержка **жирного** лида: (bold_part, rest)
            if isinstance(val, tuple):
                r0 = cp.add_run(val[0]); r0.bold = True
                if len(val) > 1 and val[1]:
                    cp.add_run(val[1])
            else:
                cp.add_run(str(val)).font.size = Pt(10)
    if widths:
        for ci, w in enumerate(widths):
            for row in t.rows:
                row.cells[ci].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t

def toc():
    p = doc.add_paragraph()
    run = p.add_run()
    fldBegin = OxmlElement('w:fldChar'); fldBegin.set(qn('w:fldCharType'), 'begin')
    instr = OxmlElement('w:instrText'); instr.set(qn('xml:space'), 'preserve')
    instr.text = 'TOC \\o "1-2" \\h \\z \\u'
    fldSep = OxmlElement('w:fldChar'); fldSep.set(qn('w:fldCharType'), 'separate')
    t = OxmlElement('w:t'); t.text = 'Оглавление обновится в Word: правый клик → «Обновить поле».'
    fldEnd = OxmlElement('w:fldChar'); fldEnd.set(qn('w:fldCharType'), 'end')
    run._r.append(fldBegin); run._r.append(instr); run._r.append(fldSep); run._r.append(t); run._r.append(fldEnd)

