# -*- coding: utf-8 -*-
"""Раздел «Добавление проекта» — общий контент для гайда и отдельного файла.

render() получает готовые помощники оформления (h1..check) и рисует раздел.
Используется и в build_guide.py (дописывает блок в гайд), и в
build_addproject.py (отдельный документ). Текст правится в одном месте.
"""
TEMPLATE_NAME = "Site Checker — эталон нового проекта.xlsx"


def render(h1, h2, h3, para, bullet, table, tip, warn, check):
    h1('Добавление проекта')
    para('Добавить новый проект — это собрать по нему данные в едином шаблоне и разложить файлы проекта в '
         'нужные папки сервиса. Работа делится на две роли: кто-то собирает данные о сайте (заполняет '
         'эталон), а разработчик кладёт готовые файлы в сервис и подключает проект. Ниже — что именно нужно.')
    tip('Все данные собираются в ОДИН эталонный файл — «' + TEMPLATE_NAME + '». Он лежит рядом с гайдом, в '
        'папке docs/templates. Заполняйте его вместо разрозненных выгрузок из CMS — тогда данные попадут в '
        'сервис без ручной подгонки под каждую таблицу.')

    # ── Шаг 1 ──
    h2('Шаг 1. Собрать данные по эталону')
    para('Скопируйте эталон и заполните его по своему проекту. На каждом листе первая строка (серая, '
         'курсив) — пример: замените её своими данными и удалите пометку «(пример)». Столбцы не '
         'переименовывайте — по их названиям сервис распознаёт данные.')
    table(
        ['Лист эталона', 'Что заполнить'],
        [
            [('Паспорт проекта',), 'Базовые сведения: код проекта, название, главный домен, sitemap, есть ли фильтры, блокирует ли сайт зарубежный IP (нужен ли прокси).'],
            [('Поддомены',), 'Все городские поддомены: url, город, страна.'],
            [('Каталог',), 'Адреса каталога и категорий; тип — «категория» или «тег» (тег = страница фильтра).'],
            [('КП (Карта присутствия)',), 'Главный лист: по каждому городу — телефоны (SEO / реклама / общий), почта, адрес, Telegram, WhatsApp.'],
            [('Формы',), 'Список форм по страницам: название, где на странице находится (шапка/подвал/модалка), URL, в каких странах есть.'],
            [('Цели',), 'Цели Яндекс.Метрики по каждому домену/стране: счётчик, № цели, название, тип, идентификатор.'],
        ],
        widths=[4.6, 11.8])
    tip('Примеры в эталоне вымышленные (домен primer.ru). Так его можно передать любому, кто добавляет '
        'проект, не открывая доступ к нашей реальной Карте присутствия — достаточно оставить 1–2 строки-примера '
        'как образец заполнения.')

    # ── Шаг 2 ──
    h2('Шаг 2. Файлы проекта')
    para('Из заполненного эталона получаются файлы проекта. Везде <id> — короткий код проекта (латиницей, '
         'например imp): он задаётся именем файла projects/<id>.json и подставляется в имена остальных файлов.')
    table(
        ['Файл', 'Нужен', 'Что внутри'],
        [
            ['projects/<id>.json', 'всегда', 'Паспорт проекта: домен, ссылки, флаги (см. ниже).'],
            ['catalogs/<id>-subdomains.csv', 'для Чек-листа', 'Поддомены: колонки url, city, country.'],
            ['catalogs/<id>-catalog.csv', 'для Чек-листа', 'Каталог: колонки url, type («категория» / «тег»).'],
            ['catalogs/<id>-kp.csv', 'для Проверки КП', 'Контакты по городам (11 колонок; собирается из эталона / Google-таблицы).'],
            ['catalogs/goals-<id>.json (+ -<страна>)', 'для Проверки целей', 'Цели Метрики по каждой стране.'],
            ['forms_tester/projects/<id>/', 'для Проверки форм', 'config.py (описание форм) + cities.csv (города).'],
            ['catalogs/filters-<id>.json', 'если есть фильтры', 'Селекторы фильтров для браузерной проверки.'],
            ['catalogs/<id>-products.csv', 'по желанию', 'База товаров (собирается раз в месяц; иначе товары берутся из sitemap.xml).'],
        ],
        widths=[5.4, 3.2, 7.8])

    h3('Паспорт проекта — projects/<id>.json')
    para('Единственный по-настоящему обязательный файл. Чтобы проект появился в списках, нужны id, name, '
         'root_domain, main_url. Чтобы он появился на вкладке «Чек-лист» — ещё subdomains_csv и catalog_csv.')
    table(
        ['Поле', 'Нужно', 'Что это'],
        [
            ['id', 'да', 'Код проекта; совпадает с именем файла <id>.json.'],
            ['name', 'да', 'Название для списков, например «ИМП — Инметпром».'],
            ['root_domain', 'да', 'Корневой домен без http:// и слэша (inmetprom.ru).'],
            ['main_url', 'да', 'Главная страница со схемой и слэшем.'],
            ['sitemap_url', 'желательно', 'Адрес sitemap.xml (запасной источник товаров).'],
            ['subdomains_csv', 'для Чек-листа', '«catalogs/<id>-subdomains.csv».'],
            ['catalog_csv', 'для Чек-листа', '«catalogs/<id>-catalog.csv».'],
            ['has_filters', 'по желанию', 'true — у проекта есть фильтры/теги.'],
            ['use_proxy', 'по желанию', 'true — сайт блокирует зарубежный IP, нужен прокси.'],
            ['kp_sheet_url', 'по желанию', 'Ссылка на Google-таблицу КП (если КП живёт в Google).'],
            ['gsc_resource', 'по желанию', 'Ресурс Google Search Console (по умолчанию sc-domain:<домен>).'],
        ],
        widths=[3.4, 3.0, 10.0])

    h3('КП (Карта присутствия)')
    para('Итоговый файл catalogs/<id>-kp.csv собирается автоматически из листа «КП» эталона (или из '
         'Google-таблицы) — вручную его набирать не нужно. В нём ровно 11 колонок в фиксированном порядке:')
    para([('domain, city, phone_seo, phone_ad, phone_common, all_phones, email, address, country, '
           'telegram, whatsapp', False, False)])
    bullet([('phone_seo / phone_ad / phone_common — ', True), ('телефоны для поиска / рекламный (коллтрекинг) / '
            'общий. Если номер один — заполняется только «Общий».',)])
    bullet([('all_phones — ', True), ('все номера города в «голом» виде через «;»; собирается автоматически, '
            'вручную не заполняется.',)])
    tip('Смысл эталона — единые названия столбцов. Когда все заполняют КП одинаково, сервис подхватывает '
        'её без подгонки под каждую таблицу. Если КП ведётся в Google-таблице — дайте доступ «по ссылке — '
        'Читатель» и укажите ссылку в поле kp_sheet_url; сервис сам подтянет свежие данные при проверке.')

    h3('Формы и цели')
    bullet([('Формы — ', True), ('лист «Формы» эталона переносится в forms_tester/projects/<id>/config.py '
            '(описание каждой формы: название, где находится, поля, кнопка отправки) и cities.csv (страна, '
            'город, url, почта). Название формы — ключ, по нему подтягивается подсказка «Где находится».',)])
    bullet([('Цели — ', True), ('лист «Цели» переносится в catalogs/goals-<id>.json (Россия) и по одному '
            'файлу goals-<id>-<страна>.json на страну (-uz, -az, -kz, -kg, -rb, -am). У каждой цели: номер, '
            'название, тип (js / auto / jivo / url / url_re), идентификатор reachGoal и условие.',)])

    h3('Прокси и доступ к сайту')
    para('Если сайт открывается только из РФ, в паспорте проекта ставится use_proxy: true, а сам адрес '
         'прокси задаётся на странице «Настройки проекта» (поле «Прокси»). Там же, в блоке проверки доступа, '
         'можно сразу убедиться, что сервис заходит на сайт (ответ 200). Если use_proxy: false — прокси не '
         'используется, даже если адрес задан.')

    # ── Шаг 3 ──
    h2('Шаг 3. Подключить проект (разработчик)')
    para('Разработчик кладёт файлы по путям выше и делает несколько правок в коде — там, где списки '
         'проектов заданы вручную:')
    bullet([('Чек-лист и главный список ', True), ('проектов подхватываются автоматически из projects/*.json '
            '— здесь править ничего не нужно.',)])
    bullet([('kp.py — ', True), ('добавить запись про КП проекта (какой лист и какие колонки телефонов '
            'использовать). Если КП заполнена по эталону — подходит стандартная запись.',)])
    bullet([('checklists/goals_check.py — ', True), ('добавить проект и его страны, чтобы они появились в «Проверке целей».',)])
    bullet([('checklists/forms_check.py — ', True), ('добавить проект в список «Проверки форм».',)])
    warn('Секреты (пароли админки, ключ сервисного аккаунта Google для приватной КП, адрес прокси) в '
         'репозиторий не кладутся — они задаются в секретах приложения или на странице «Настройки проекта».')
    para('После этого проект появляется в нужных вкладках, и по нему можно запускать проверки так же, как по '
         'остальным.')
